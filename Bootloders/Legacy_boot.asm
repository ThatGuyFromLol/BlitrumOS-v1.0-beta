    ; =============================================================================
; Blitrum OS - Legacy BIOS Bootloader
; Stage 1
;
; 16-bit Real Mode
;      |
;      +-- load Stage 2
;      |
;      +-- enable A20
;      |
;      +-- enter 32-bit Protected Mode
;      |
;      +-- jump to Stage 2
;
; BIOS loads this sector at 0000:7C00
; =============================================================================

bits 16
org 0x7C00

; -----------------------------------------------------------------------------
; Configuration
; -----------------------------------------------------------------------------

STAGE2_ADDRESS  equ 0x8000

; Stage 2 occupies sectors immediately after boot sector.
;
; 1 = 512 bytes
; 16 = 8192 bytes
;
; Na początek zostawiamy 16 sektorów.
; Później build.sh może policzyć to automatycznie.
;
STAGE2_SECTORS  equ 16

; -----------------------------------------------------------------------------
; Start
; -----------------------------------------------------------------------------

_start:

    cli

    ; ---------------------------------------------------------
    ; Save BIOS boot drive
    ; DL = drive number
    ; ---------------------------------------------------------

    mov [boot_drive], dl
    mov [4FF0],dl
    ; ---------------------------------------------------------
    ; Initialize segments
    ; ---------------------------------------------------------

    xor ax, ax

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov sp, 0x7C00

    ; ---------------------------------------------------------
    ; Load Stage 2
    ;
    ; BIOS:
    ;   AH = 02h
    ;   AL = sectors
    ;   CH = cylinder
    ;   CL = sector
    ;   DH = head
    ;   DL = drive
    ;
    ; Stage 2:
    ;   physical address 0x8000
    ; ---------------------------------------------------------

    mov ax, 0x0000
    mov es, ax

    mov bx, STAGE2_ADDRESS

    mov ah, 0x02
    mov al, STAGE2_SECTORS

    mov ch, 0
    mov cl, 2

    mov dh, 0

    mov dl, [boot_drive]

    int 0x13

    jc disk_error

    ; ---------------------------------------------------------
    ; Enable A20
    ; ---------------------------------------------------------

    call enable_a20

    ; ---------------------------------------------------------
    ; Load 32-bit GDT
    ; ---------------------------------------------------------

    lgdt [gdt_descriptor]

    ; ---------------------------------------------------------
    ; Enter Protected Mode
    ; CR0.PE = 1
    ; ---------------------------------------------------------

    mov eax, cr0

    or eax, 0x00000001

    mov cr0, eax

    ; ---------------------------------------------------------
    ; Far jump is REQUIRED after enabling PE.
    ;
    ; This flushes the CPU prefetch queue and loads CS.
    ; ---------------------------------------------------------

    jmp CODE32_SELECTOR:protected_mode


; =============================================================================
; A20
; =============================================================================

enable_a20:

    in al, 0x92

    or al, 00000010b

    and al, 11111110b

    out 0x92, al

    ret


; =============================================================================
; Disk error
; =============================================================================

disk_error:

    mov si, disk_error_message

.print:

    lodsb

    test al, al

    jz .halt

    mov ah, 0x0E

    mov bh, 0

    int 0x10

    jmp .print


.halt:

    cli

    hlt

    jmp .halt


disk_error_message:

    db "BLITRUM: Stage2 disk error", 13, 10, 0


; =============================================================================
; BIOS boot drive
; =============================================================================

boot_drive:

    db 0


; =============================================================================
; 32-bit GDT
; =============================================================================

align 8

gdt_start:

    ; -------------------------------------------------------------------------
    ; Null descriptor
    ; -------------------------------------------------------------------------

    dq 0x0000000000000000


    ; -------------------------------------------------------------------------
    ; 32-bit Code
    ;
    ; Base  = 0
    ; Limit = 4 GB
    ; Present
    ; Ring 0
    ; Code
    ; 32-bit
    ; -------------------------------------------------------------------------

    dq 0x00CF9A000000FFFF


    ; -------------------------------------------------------------------------
    ; 32-bit Data
    ;
    ; Base  = 0
    ; Limit = 4 GB
    ; Present
    ; Ring 0
    ; Data
    ; -------------------------------------------------------------------------

    dq 0x00CF92000000FFFF


gdt_end:


gdt_descriptor:

    dw gdt_end - gdt_start - 1

    dd gdt_start


; -----------------------------------------------------------------------------
; GDT selectors
; -----------------------------------------------------------------------------

CODE32_SELECTOR equ 0x08
DATA32_SELECTOR equ 0x10


; =============================================================================
; 32-bit Protected Mode
; =============================================================================

bits 32

protected_mode:

    ; -------------------------------------------------------------------------
    ; Load 32-bit data segments
    ; -------------------------------------------------------------------------

    mov ax, DATA32_SELECTOR

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov fs, ax
    mov gs, ax

    ; -------------------------------------------------------------------------
    ; 32-bit stack
    ; -------------------------------------------------------------------------

    mov esp, 0x90000

    ; -------------------------------------------------------------------------
    ; Stage 2 was loaded by BIOS at physical 0x8000.
    ;
    ; Because we use a flat GDT:
    ;
    ; virtual/linear 0x8000
    ;          =
    ; physical       0x8000
    ;
    ; Jump directly to Stage 2.
    ; -------------------------------------------------------------------------

    jmp STAGE2_ADDRESS


; =============================================================================
; Boot sector padding
; =============================================================================

times 510 - ($ - $$) db 0

dw 0xAA55