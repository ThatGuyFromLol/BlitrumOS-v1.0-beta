; =============================================================================
;                         BLITRUM OS - LEGACY BIOS
;                              STAGE 1
; =============================================================================
;
; Wejście:
;   BIOS
;   CPU = 16-bit Real Mode
;   BIOS ładuje sektor 0 pod 0000:7C00
;
; Zadanie:
;   1. Zapisać numer dysku
;   2. Sprawdzić INT 13h Extensions
;   3. Załadować Stage 2 pod 0x8000
;   4. Włączyć A20
;   5. Wejść w 32-bit Protected Mode
;   6. Skoczyć do Stage 2
;
; Stage 2:
;   fizycznie = 0x8000
;
; =============================================================================

bits 16
org 0x7C00

; =============================================================================
; KONFIGURACJA
; =============================================================================

STAGE2_ADDRESS      equ 0x8000

; Aktualny Stage 2 posiada własne page tables:
;
; PML4 = 4096
; PDPT = 4096
; PD   = 4096
;
; plus kod.
;
; 35 sektorów = 17920 bajtów.
;
STAGE2_SECTORS      equ 35

BOOT_DRIVE_MEMORY   equ 0x4FF0

; =============================================================================
; START
; =============================================================================

_start:

    cli

    ; -------------------------------------------------------------------------
    ; Ujednolicenie CS = 0
    ;
    ; BIOS może uruchomić nas jako:
    ;
    ;   0000:7C00
    ;
    ; ale chcemy mieć pewność, że:
    ;
    ;   CS = 0000
    ;   IP = 7C00
    ;
    ; Dzięki temu wszystkie adresy ORG 0x7C00 są jednoznaczne.
    ; -------------------------------------------------------------------------

    push word 0x0000
    push word .real_start
    retf

.real_start:

    ; -------------------------------------------------------------------------
    ; Zachowaj numer dysku
    ; DL = BIOS boot drive
    ; -------------------------------------------------------------------------

    mov [boot_drive], dl
    mov [BOOT_DRIVE_MEMORY], dl

    ; -------------------------------------------------------------------------
    ; Segmenty
    ; -------------------------------------------------------------------------

    xor ax, ax

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov sp, 0x7C00

    ; -------------------------------------------------------------------------
    ; Zachowaj numer dysku jeszcze raz po inicjalizacji segmentów
    ; -------------------------------------------------------------------------

    mov dl, [boot_drive]

    ; =========================================================================
    ; SPRAWDZENIE INT 13h EXTENSIONS
    ; =========================================================================

    mov ah, 0x41
    mov bx, 0x55AA
    int 0x13

    jc disk_extensions_error

    cmp bx, 0xAA55
    jne disk_extensions_error

    test cx, 1
    jz disk_extensions_error

    ; =========================================================================
    ; PRZYGOTOWANIE DAP
    ; =========================================================================

    ; DAP:
    ;
    ; +0  BYTE  size = 0x10
    ; +1  BYTE  reserved
    ; +2  WORD  number of sectors
    ; +4  WORD  offset
    ; +6  WORD  segment
    ; +8  DWORD LBA low
    ; +12 DWORD LBA high
    ;
    ; Stage 1 = LBA 0
    ; Stage 2 = LBA 1
    ;
    ; Destination = 0000:8000
    ; -------------------------------------------------------------------------

    mov byte [dap + 0], 0x10
    mov byte [dap + 1], 0x00

    mov word [dap + 2], STAGE2_SECTORS

    mov word [dap + 4], STAGE2_ADDRESS
    mov word [dap + 6], 0x0000

    mov dword [dap + 8], 1
    mov dword [dap + 12], 0

    ; =========================================================================
    ; RESET BIOS DISK
    ; =========================================================================

    xor ah, ah
    mov dl, [boot_drive]
    int 0x13

    ; =========================================================================
    ; LOAD STAGE 2
    ; =========================================================================

    mov si, dap
    mov dl, [boot_drive]

    mov ah, 0x42
    int 0x13
    jc stage2_disk_error

    ; =========================================================================
    ; ODCZYT ZAKOŃCZONY
    ;
    ; Nie sprawdzamy DAP.count.
    ;
    ; INT 13h AH=42h sygnalizuje błąd przez CF.
    ; BIOS nie musi zachowywać DAP.count w formie, której oczekujemy.
    ; =========================================================================

    ; =========================================================================
    ; STAGE 2 JEST JUŻ W RAM
    ;
    ; TERAZ dopiero:
    ;
    ;   A20
    ;   GDT
    ;   Protected Mode
    ;   jump 0x8000
    ; =========================================================================

    call enable_a20

    lgdt [gdt_descriptor]

    ; -------------------------------------------------------------------------
    ; Protected Mode
    ; -------------------------------------------------------------------------

    mov eax, cr0
    or eax, 0x00000001
    mov cr0, eax

    ; -------------------------------------------------------------------------
    ; Far jump:
    ; wymagany po ustawieniu CR0.PE
    ; -------------------------------------------------------------------------

    jmp CODE32_SELECTOR:protected_mode_entry


; =============================================================================
; A20
; =============================================================================

enable_a20:

    ; Fast A20 Gate przez port 0x92

    in al, 0x92

    or al, 00000010b
    and al, 11111110b

    out 0x92, al

    ret


; =============================================================================
; PROTECTED MODE
; =============================================================================

bits 32

protected_mode_entry:

    ; -------------------------------------------------------------------------
    ; Segmenty
    ; -------------------------------------------------------------------------

    mov ax, DATA32_SELECTOR

    mov ds, ax
    mov es, ax
    mov ss, ax
    mov fs, ax
    mov gs, ax

    ; -------------------------------------------------------------------------
    ; Stack
    ; -------------------------------------------------------------------------

    mov esp, 0x90000

    ; -------------------------------------------------------------------------
    ; Stage 2:
    ;
    ; 0x8000 = adres liniowy = adres fizyczny
    ;
    ; GDT ma bazę 0.
    ; -------------------------------------------------------------------------

    mov eax, STAGE2_ADDRESS

    jmp eax


; =============================================================================
; DISK ERROR
; =============================================================================

bits 16

stage2_disk_error:

    mov si, stage2_error_message

.print:

    lodsb

    test al, al
    jz .halt

    mov ah, 0x0E
    mov bh, 0

    int 0x10

    jmp .print

.halt:

    cli

    hlt

    jmp .halt


; =============================================================================
; INT 13 EXTENSIONS ERROR
; =============================================================================

disk_extensions_error:

    mov si, extensions_error_message

.print:

    lodsb

    test al, al
    jz .halt

    mov ah, 0x0E
    mov bh, 0

    int 0x10

    jmp .print

.halt:

    cli

    hlt

    jmp .halt


; =============================================================================
; KOMUNIKATY
; =============================================================================

stage2_error_message:

    db "BLITRUM: Stage2 disk error", 13, 10, 0


extensions_error_message:

    db "BLITRUM: BIOS INT13 extensions error", 13, 10, 0


; =============================================================================
; BOOT DRIVE
; =============================================================================

boot_drive:

    db 0


; =============================================================================
; DISK ADDRESS PACKET
; =============================================================================

align 4

dap:

    db 0x10
    db 0x00

    dw 0

    dw 0
    dw 0

    dd 0
    dd 0


; =============================================================================
; GDT
; =============================================================================

align 8

gdt_start:

    ; -------------------------------------------------------------------------
    ; NULL
    ; -------------------------------------------------------------------------

    dq 0x0000000000000000

    ; -------------------------------------------------------------------------
    ; 32-bit CODE
    ;
    ; Base  = 0
    ; Limit = 4 GB
    ; Present
    ; Ring 0
    ; Code
    ; 32-bit
    ; -------------------------------------------------------------------------

    dq 0x00CF9A000000FFFF

    ; -------------------------------------------------------------------------
    ; 32-bit DATA
    ; -------------------------------------------------------------------------

    dq 0x00CF92000000FFFF


gdt_end:


gdt_descriptor:

    dw gdt_end - gdt_start - 1

    dd gdt_start


; =============================================================================
; SELECTORS
; =============================================================================

CODE32_SELECTOR equ 0x08
DATA32_SELECTOR equ 0x10


; =============================================================================
; BOOT SECTOR
; =============================================================================

times 510 - ($ - $$) db 0

dw 0xAA55