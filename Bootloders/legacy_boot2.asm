
    ; =============================================================================
; BLITRUM OS - LEGACY BOOTLOADER
; STAGE 2
;
; Wejście:
;   CPU        = 32-bit Protected Mode
;   Stage 2    = 0x00008000
;
; Wyjście:
;   CPU        = x86-64 Long Mode
;   Kernel     = 0x00100000
;
; Pamięć:
;
;   0x4FF0      BIOS boot drive
;   0x5000      BOOTINFO
;   0x6000      E820 memory map
;   0x20000     tymczasowy kernel
;   0x90000     stack
;   0x100000    właściwy kernel
;
; =============================================================================

bits 32
org 0x8000


; =============================================================================
; MEMORY LAYOUT
; =============================================================================

BOOT_DRIVE          equ 0x00004FF0
BOOTINFO            equ 0x00005000
E820_BUFFER         equ 0x00006000

KERNEL_TEMP         equ 0x00020000
KERNEL_ADDRESS      equ 0x00100000

STACK32             equ 0x000B0000
STACK64             equ 0x000B0000

PML4_ADDRESS        equ 0x00070000
PDPT_ADDRESS        equ 0x00071000
PD_ADDRESS          equ 0x00072000


; =============================================================================
; DISK CONFIGURATION
; =============================================================================

; Stage 1 = sektor 1
; Stage 2 = sektory 2... (35 sektory)
; Kernel zaczyna się od LBA 36+

KERNEL_LBA          equ 36

; Maksymalny rozmiar kernela:
; 1024 * 512 = 512 KiB

KERNEL_SECTORS      equ 1024

; Jeden transfer BIOS
; 32 sektory = 16 KiB

READ_CHUNK          equ 32


; =============================================================================
; STAGE 2 ENTRY
; =============================================================================

stage2_start:

    cli

    ; -------------------------------------------------------------------------
    ; Segmenty 32-bit
    ; -------------------------------------------------------------------------

    mov ax, DATA32_SELECTOR

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov fs, ax
    mov gs, ax

    mov esp, STACK32

    ; -------------------------------------------------------------------------
    ; Numer dysku przekazany przez Stage 1
    ; -------------------------------------------------------------------------

    mov al, [BOOT_DRIVE]

    mov [boot_drive], al

    ; -------------------------------------------------------------------------
    ; Przejście do Real Mode.
    ;
    ; Potrzebujemy BIOS:
    ;
    ; INT 15h E820
    ; INT 13h Extensions
    ; -------------------------------------------------------------------------

    call protected_to_real


; =============================================================================
; REAL MODE
; =============================================================================

bits 16

real_mode_start:

    cli

    xor ax, ax

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov sp, 0x7C00

    ; -------------------------------------------------------------------------
    ; Pobierz mapę pamięci E820
    ; -------------------------------------------------------------------------

    call collect_e820

    ; -------------------------------------------------------------------------
    ; Załaduj kernel do 0x20000
    ; -------------------------------------------------------------------------

    call load_kernel

    ; -------------------------------------------------------------------------
    ; Powrót do Protected Mode
    ; -------------------------------------------------------------------------

    call real_to_protected


; =============================================================================
; Ta etykieta jest tylko punktem przejścia.
; Po real_to_protected CPU wykona skok do protected_mode_entry.
; =============================================================================


; =============================================================================
; E820 MEMORY MAP
; =============================================================================

collect_e820:

    xor ebx, ebx

    mov di, E820_BUFFER

    xor bp, bp


.e820_loop:

    mov eax, 0xE820

    mov edx, 0x534D4150        ; "SMAP"

    mov ecx, 24

    int 0x15

    jc .done

    cmp eax, 0x534D4150

    jne .done

    ; -------------------------------------------------------------------------
    ; Jeden wpis E820 = 24 bajty
    ; -------------------------------------------------------------------------

    add di, 24

    inc bp

    ; -------------------------------------------------------------------------
    ; BIOS ustawia EBX = continuation value.
    ; EBX = 0 oznacza koniec.
    ; -------------------------------------------------------------------------

    cmp ebx, 0

    jne .e820_loop


.done:

    ; -------------------------------------------------------------------------
    ; BOOTINFO
    ;
    ; +0   = signature "BIOS"
    ; +8   = E820 address
    ; +16  = liczba wpisów
    ; +24  = rozmiar wpisu
    ; +32  = framebuffer address
    ; +40  = width
    ; +44  = height
    ; +48  = pixels per scanline
    ; -------------------------------------------------------------------------

    mov dword [BOOTINFO + 0], 0x42494F53
    mov dword [BOOTINFO + 4], 0

    mov dword [BOOTINFO + 8], E820_BUFFER

    mov word [BOOTINFO + 16], bp

    mov word [BOOTINFO + 24], 24

    ; -------------------------------------------------------------------------
    ; Legacy BIOS:
    ; brak GOP framebuffer
    ; -------------------------------------------------------------------------

    mov dword [BOOTINFO + 32], 0
    mov dword [BOOTINFO + 36], 0

    mov dword [BOOTINFO + 40], 0
    mov dword [BOOTINFO + 44], 0
    mov dword [BOOTINFO + 48], 0

    ret


; =============================================================================
; LOAD KERNEL
;
; Ładujemy kernel kawałkami po 32 sektory.
;
; BIOS:
;
;   INT 13h
;   AH = 42h
;
; =============================================================================

load_kernel:

    mov word [current_sector_count], KERNEL_SECTORS

    mov dword [current_lba_low], KERNEL_LBA

    mov dword [current_destination], KERNEL_TEMP


.load_loop:

    cmp word [current_sector_count], 0

    je .done


    ; -------------------------------------------------------------------------
    ; Ile sektorów zostało?
    ; -------------------------------------------------------------------------

    mov ax, [current_sector_count]

    cmp ax, READ_CHUNK

    jbe .small_chunk

    mov ax, READ_CHUNK


.small_chunk:

    mov [dap.count], ax

    ; -------------------------------------------------------------------------
    ; Destination -> segment:offset
    ;
    ; KERNEL_TEMP + offset
    ; -------------------------------------------------------------------------

    mov eax, [current_destination]

    mov bx, ax

    and bx, 0x000F

    mov [dap.offset], bx

    shr eax, 4

    mov [dap.segment], ax

    ; -------------------------------------------------------------------------
    ; LBA
    ; -------------------------------------------------------------------------

    mov eax, [current_lba_low]

    mov [dap.lba_low], eax

    mov dword [dap.lba_high], 0

    ; -------------------------------------------------------------------------
    ; BIOS drive
    ; -------------------------------------------------------------------------

    mov dl, [boot_drive]

    mov si, dap

    mov ah, 0x42

    int 0x13

    jc kernel_disk_error

    ; -------------------------------------------------------------------------
    ; Ile sektorów faktycznie odczytaliśmy
    ; -------------------------------------------------------------------------

    mov ax, [dap.count]

    ; -------------------------------------------------------------------------
    ; current_lba += count
    ; -------------------------------------------------------------------------

    movzx eax, ax

    add [current_lba_low], eax

    ; -------------------------------------------------------------------------
    ; destination += count * 512
    ; -------------------------------------------------------------------------

    shl eax, 9

    add [current_destination], eax

    ; -------------------------------------------------------------------------
    ; remaining -= count
    ; -------------------------------------------------------------------------

    mov ax, [dap.count]

    sub [current_sector_count], ax

    jmp .load_loop


.done:

    ret


; =============================================================================
; PROTECTED MODE -> REAL MODE
; =============================================================================

bits 32

protected_to_real:

    cli

    ; -------------------------------------------------------------------------
    ; Wyłącz paging
    ; -------------------------------------------------------------------------

    mov eax, cr0

    and eax, 0x7FFFFFFF

    mov cr0, eax

    ; -------------------------------------------------------------------------
    ; Wyłącz Protected Mode
    ; -------------------------------------------------------------------------

    mov eax, cr0

    and eax, 0xFFFFFFFE

    mov cr0, eax

    ; -------------------------------------------------------------------------
    ; Far jump do Real Mode
    ; -------------------------------------------------------------------------

    jmp 0x0000:real_mode_start


; =============================================================================
; REAL MODE -> PROTECTED MODE
; =============================================================================

bits 16

real_to_protected:

    cli

    ; -------------------------------------------------------------------------
    ; Załaduj GDT
    ; -------------------------------------------------------------------------

    lgdt [gdt_descriptor16]

    ; -------------------------------------------------------------------------
    ; Włącz Protected Mode
    ; -------------------------------------------------------------------------

    mov eax, cr0

    or eax, 1

    mov cr0, eax

    ; -------------------------------------------------------------------------
    ; Far jump
    ; -------------------------------------------------------------------------

    jmp CODE32_SELECTOR:protected_mode_entry


; =============================================================================
; PROTECTED MODE ENTRY
; =============================================================================

bits 32

protected_mode_entry:

    mov ax, DATA32_SELECTOR

    mov ds, ax
    mov es, ax
    mov ss, ax

    mov fs, ax
    mov gs, ax

    mov esp, STACK32

    ; -------------------------------------------------------------------------
    ; Kernel znajduje się obecnie pod 0x20000.
    ;
    ; Przenieśmy go pod 0x100000.
    ;
    ; 1024 * 512 = 512 KiB.
    ; -------------------------------------------------------------------------

    cld

    mov esi, KERNEL_TEMP

    mov edi, KERNEL_ADDRESS

    mov ecx, (KERNEL_SECTORS * 512) / 4

    rep movsd

    ; -------------------------------------------------------------------------
    ; Przygotuj paging
    ; -------------------------------------------------------------------------

    call setup_page_tables

    ; -------------------------------------------------------------------------
    ; PAE
    ; -------------------------------------------------------------------------

    mov eax, cr4

    or eax, (1 << 5)

    mov cr4, eax

    ; -------------------------------------------------------------------------
    ; CR3 = PML4
    ; -------------------------------------------------------------------------

    mov eax, PML4_ADDRESS

    mov cr3, eax

    ; -------------------------------------------------------------------------
    ; Enable Long Mode
    ;
    ; IA32_EFER
    ; -------------------------------------------------------------------------

    mov ecx, 0xC0000080

    rdmsr

    or eax, (1 << 8)

    wrmsr

    ; -------------------------------------------------------------------------
    ; Enable paging
    ; -------------------------------------------------------------------------

    mov eax, cr0

    or eax, (1 << 31)

    mov cr0, eax

    ; -------------------------------------------------------------------------
    ; Far jump into 64-bit mode
    ; -------------------------------------------------------------------------

    jmp CODE64_SELECTOR:long_mode


; =============================================================================
; PAGE TABLES
;
; Identity map:
;
; 0x00000000 -> 0x001FFFFF
;
; przy użyciu jednej strony 2 MiB.
;
; Dzięki temu:
;
; 0x100000 kernel
;
; pozostaje dostępny.
; =============================================================================

setup_page_tables:

    ; -------------------------------------------------------------------------
    ; Wyczyść PML4
    ; -------------------------------------------------------------------------

    mov edi, PML4_ADDRESS

    xor eax, eax

    mov ecx, 1024

    rep stosd

    ; -------------------------------------------------------------------------
    ; Wyczyść PDPT
    ; -------------------------------------------------------------------------

    mov edi, PDPT_ADDRESS

    xor eax, eax

    mov ecx, 1024

    rep stosd

    ; -------------------------------------------------------------------------
    ; Wyczyść PD
    ; -------------------------------------------------------------------------

    mov edi, PD_ADDRESS

    xor eax, eax

    mov ecx, 1024

    rep stosd

    ; -------------------------------------------------------------------------
    ; PML4[0] -> PDPT
    ;
    ; Present = 1
    ; Writable = 1
    ; -------------------------------------------------------------------------

    mov eax, PDPT_ADDRESS

    or eax, 0x03

    mov [PML4_ADDRESS], eax

    ; -------------------------------------------------------------------------
    ; PDPT[0] -> PD
    ; -------------------------------------------------------------------------

    mov eax, PD_ADDRESS

    or eax, 0x03

    mov [PDPT_ADDRESS], eax

    ; -------------------------------------------------------------------------
    ; PD[0] = 2 MiB page
    ;
    ; Present
    ; Writable
    ; Page Size
    ; -------------------------------------------------------------------------

    mov eax, 0x00000083

    mov [PD_ADDRESS], eax

    ret


; =============================================================================
; LONG MODE
; =============================================================================

bits 64

long_mode:

    cli

    ; -------------------------------------------------------------------------
    ; Segmenty danych
    ; -------------------------------------------------------------------------

    mov ax, DATA32_SELECTOR

    mov ds, ax
    mov es, ax
    mov ss, ax

    ; -------------------------------------------------------------------------
    ; Stack
    ; -------------------------------------------------------------------------

    mov rsp, STACK64

    ; -------------------------------------------------------------------------
    ; INTERFEJS DLA KERNEL.ASM
    ;
    ; kernel:
    ;
    ; cmp rdx, 0x554...
    ; cmp rcx, 0x42494F53
    ;
    ; Legacy = RCX
    ; -------------------------------------------------------------------------

    mov rcx, 0x42494F53

    ; -------------------------------------------------------------------------
    ; R8 = aktualny CR3
    ; -------------------------------------------------------------------------

    mov r8, cr3

    ; -------------------------------------------------------------------------
    ; R9 = framebuffer
    ;
    ; Legacy BIOS nie posiada GOP.
    ; -------------------------------------------------------------------------

    xor r9, r9

    ; -------------------------------------------------------------------------
    ; Skok do kernela
    ; -------------------------------------------------------------------------

    mov rax, KERNEL_ADDRESS

    jmp rax


; =============================================================================
; DISK ERROR
; =============================================================================

bits 16

kernel_disk_error:

    mov si, kernel_error_message


.error_loop:

    lodsb

    test al, al

    jz .halt

    mov ah, 0x0E

    mov bh, 0

    int 0x10

    jmp .error_loop


.halt:

    cli

    hlt

    jmp .halt


kernel_error_message:

    db "BLITRUM: KERNEL LOAD ERROR", 13, 10, 0


; =============================================================================
; BIOS DISK ADDRESS PACKET
; =============================================================================

align 4

dap:

    db 0x10
    db 0x00

.count:

    dw 0

.offset:

    dw 0

.segment:

    dw 0

.lba_low:

    dd 0

.lba_high:

    dd 0


; =============================================================================
; VARIABLES
; =============================================================================

align 4

boot_drive:

    db 0

current_sector_count:

    dw 0

current_lba_low:

    dd 0

current_destination:

    dd 0


; =============================================================================
; GDT
; =============================================================================

align 8

gdt_start:

    ; Null
    dq 0x0000000000000000

    ; 32-bit code
    dq 0x00CF9A000000FFFF

    ; 32-bit data
    dq 0x00CF92000000FFFF

    ; 64-bit code
    dq 0x00AF9A000000FFFF


gdt_end:


gdt_descriptor16:

    dw gdt_end - gdt_start - 1

    dd gdt_start


; =============================================================================
; SELECTORS
; =============================================================================

CODE32_SELECTOR equ 0x08
DATA32_SELECTOR equ 0x10
CODE64_SELECTOR equ 0x18


; =============================================================================
; PAGE TABLE MEMORY
; =============================================================================

align 4096

PML4:

    times 512 dq 0

PDPT:

    times 512 dq 0

PD:

    times 512 dq 0


; =============================================================================
; END
; =============================================================================

stage2_end:  

STAGE2_MAX_SIZE equ 35 * 512

%if (stage2_end - $$) > STAGE2_MAX_SIZE
    %error "Stage 2 is larger than 35 sectors!"
%endif

times STAGE2_MAX_SIZE - (stage2_end - $$) db 0