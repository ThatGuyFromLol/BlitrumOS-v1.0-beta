; ==============================================================================
; KERNEL ENTRY
; ==============================================================================

_start:

    cli


    ; ==========================================================================
    ; SPRAWDŹ BOOTINFO
    ; ==========================================================================

    test rcx, rcx

    jz kernel_panic


    ; ==========================================================================
    ; ZACHOWAJ ADRES BOOTINFO
    ; ==========================================================================

    mov rbx, rcx


    ; ==========================================================================
    ; USTAW STOS KERNELA
    ; ==========================================================================

    lea rsp, [rel stack_top]

    and rsp, -16


    ; ==========================================================================
    ; ZAŁADUJ GDT
    ; ==========================================================================

    call gdt_init


    ; ==========================================================================
    ; WYCZYŚĆ .BSS
    ; ==========================================================================

    mov rdi, __bss_start

    mov rcx, __bss_end

    sub rcx, rdi

    xor rax, rax

    rep stosb


    ; ==========================================================================
    ; FRAMEBUFFER ADDRESS
    ; ==========================================================================

    mov r14, [rbx + 0x00]

    mov [fb_address], r14


    ; ==========================================================================
    ; FRAMEBUFFER SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x08]

    mov [fb_size], rax


    ; ==========================================================================
    ; SCREEN WIDTH
    ; ==========================================================================

    mov eax, [rbx + 0x10]

    mov [fb_width], eax


    ; ==========================================================================
    ; SCREEN HEIGHT
    ; ==========================================================================

    mov eax, [rbx + 0x14]

    mov [fb_height], eax


    ; ==========================================================================
    ; PIXELS PER SCANLINE
    ; ==========================================================================

    mov eax, [rbx + 0x18]

    mov [fb_pps], eax


    ; ==========================================================================
    ; GOP PIXEL FORMAT
    ; ==========================================================================

    mov eax, [rbx + 0x1C]

    mov [fb_pixel_format], eax

    mov [gui_pixel_format], eax


    ; ==========================================================================
    ; UEFI MEMORY MAP POINTER
    ; ==========================================================================

    mov rax, [rbx + 0x20]

    mov [mmap_ptr], rax


    ; ==========================================================================
    ; UEFI MEMORY MAP SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x28]

    mov [mmap_size], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x30]

    mov [mmap_descsz], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR VERSION
    ; ==========================================================================

    mov rax, [rbx + 0x38]

    mov [mmap_descver], rax


    ; ==========================================================================
    ; WALIDACJA BOOTINFO
    ; ==========================================================================

    cmp qword [fb_address], 0

    je kernel_panic


    cmp dword [fb_width], 0

    je kernel_panic


    cmp dword [fb_height], 0

    je kernel_panic


    cmp dword [fb_pps], 0

    je kernel_panic


    cmp qword [mmap_ptr], 0

    je kernel_panic


    cmp qword [mmap_size], 0

    je kernel_panic


    cmp qword [mmap_descsz], 0

    je