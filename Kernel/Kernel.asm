; ==============================================================================
;          BLITRUM OS - MAIN KERNEL
;          x86-64 / NASM
; ==============================================================================

bits 64

section .text

global _start

extern __bss_start
extern __bss_end


; ==============================================================================
; SYSTEM
; ==============================================================================

extern gdt_init
extern pit_init
extern bsod_init
extern serial_init
extern serial_log


; ==============================================================================
; HID / IDT
; ==============================================================================

extern hid_init
extern idt_init


; ==============================================================================
; PMM
; ==============================================================================

extern pmm_init
extern pmm_alloc_page


; ==============================================================================
; GUI
; ==============================================================================

extern gui_init
extern gui_draw_window
extern gui_refresh_screen
extern gui_pixel_format


; ==============================================================================
; STORAGE
; ==============================================================================

extern find_ahci_controller
extern init_ahci_controller
extern vfs_mount_drive
extern tgfs_load_and_map_file


; ==============================================================================
; USB / AUDIO
; ==============================================================================

extern find_usb_controllers
extern usb_interrupts_init

extern find_hda_controller
extern init_hda_controller


; ==============================================================================
; SCHEDULER
; ==============================================================================

extern scheduler_init
extern scheduler_create_task
extern scheduler_trigger_event
extern scheduler_event_loop


; ==============================================================================
; SHELL
; ==============================================================================

extern shell_init
extern shell_run


; ==============================================================================
; AHS-TUS / UPDATE
; ==============================================================================

extern update_system_init
extern update_register_vector
extern update_check
extern update_apply
extern update_is_pending


; ==============================================================================
; AHS-TUS VECTORS
; ==============================================================================

VECTOR_AUDIO    equ 0
VECTOR_USB      equ 1
VECTOR_STORAGE  equ 2
VECTOR_GRAPHICS equ 3


; ==============================================================================
; GOP PIXEL FORMAT
; ==============================================================================

PIXEL_RED_GREEN_BLUE_RESERVED equ 0
PIXEL_BLUE_GREEN_RED_RESERVED equ 1


; ==============================================================================
; KERNEL ENTRY
; ==============================================================================

_start:

    cli


    ; ==========================================================================
    ; SPRAWDŹ BOOTINFO
    ; ==========================================================================

    test rcx, rcx

    jz kernel_panic


    ; ==========================================================================
    ; ZACHOWAJ ADRES BOOTINFO
    ; ==========================================================================

    mov rbx, rcx


    ; ==========================================================================
    ; USTAW STOS KERNELA
    ; ==========================================================================

    lea rsp, [rel stack_top]

    and rsp, -16


    ; ==========================================================================
    ; ZAŁADUJ GDT
    ; ==========================================================================

    call gdt_init


    ; ==========================================================================
    ; WYCZYŚĆ .BSS
    ; ==========================================================================

    mov rdi, __bss_start

    mov rcx, __bss_end

    sub rcx, rdi

    xor rax, rax

    rep stosb


    ; ==========================================================================
    ; FRAMEBUFFER ADDRESS
    ; ==========================================================================

    mov r14, [rbx + 0x00]

    mov [fb_address], r14


    ; ==========================================================================
    ; FRAMEBUFFER SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x08]

    mov [fb_size], rax


    ; ==========================================================================
    ; SCREEN WIDTH
    ; ==========================================================================

    mov eax, [rbx + 0x10]

    mov [fb_width], eax


    ; ==========================================================================
    ; SCREEN HEIGHT
    ; ==========================================================================

    mov eax, [rbx + 0x14]

    mov [fb_height], eax


    ; ==========================================================================
    ; PIXELS PER SCANLINE
    ; ==========================================================================

    mov eax, [rbx + 0x18]

    mov [fb_pps], eax


    ; ==========================================================================
    ; GOP PIXEL FORMAT
    ; ==========================================================================

    mov eax, [rbx + 0x1C]

    mov [fb_pixel_format], eax

    mov [gui_pixel_format], eax


    ; ==========================================================================
    ; UEFI MEMORY MAP POINTER
    ; ==========================================================================

    mov rax, [rbx + 0x20]

    mov [mmap_ptr], rax


    ; ==========================================================================
    ; UEFI MEMORY MAP SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x28]

    mov [mmap_size], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x30]

    mov [mmap_descsz], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR VERSION
    ; ==========================================================================

    mov rax, [rbx + 0x38]

    mov [mmap_descver], rax


    ; ==========================================================================
    ; WALIDACJA BOOTINFO
    ; ==========================================================================

    cmp qword [fb_address], 0

    je kernel_panic


    cmp dword [fb_width], 0

    je kernel_panic


    cmp dword [fb_height], 0

    je kernel_panic


    cmp dword [fb_pps], 0

    je kernel_panic


    cmp qword [mmap_ptr], 0

    je kernel_panic


    cmp qword [mmap_size], 0

    je kernel_panic


    cmp qword [mmap_descsz], 0

    je kernel_panic


    ; ==========================================================================
    ; PMM INIT
    ;
    ; RCX = descriptor size
    ; R8  = memory map size
    ; R9  = memory map pointer
    ; ==========================================================================

    mov rcx, [mmap_descsz]

    mov r8, [mmap_size]

    mov r9, [mmap_ptr]

    call pmm_init


    ; ==========================================================================
    ; AHS-TUS
    ; ==========================================================================

    call update_system_init


    ; ==========================================================================
    ; IDT
    ;
    ; Nadal nie włączamy przerwań.
    ; ==========================================================================

    call idt_init


    ; ==========================================================================
    ; GUI / HDR
    ; ==========================================================================

    mov rcx, r14

    mov edx, [fb_width]

    mov r8d, [fb_height]

    mov r9d, [fb_pps]

    call gui_init


    ; ==========================================================================
    ; ZAREJESTRUJ GUI W AHS-TUS
    ; ==========================================================================

    mov rcx, VECTOR_GRAPHICS

    lea rdx, [rel gui_refresh_screen]

    call update_register_vector


    ; ==========================================================================
    ; AUDIO
    ; ==========================================================================

    call find_hda_controller

    jc .skip_audio


    call init_hda_controller


    mov rcx, VECTOR_AUDIO

    mov rdx, rax

    call update_register_vector


.skip_audio:


    ; ==========================================================================
    ; USB / xHCI
    ; ==========================================================================

    call find_usb_controllers

    jc .skip_usb


    mov [xhci_base_mmio], rax

    mov rcx, rax

    call usb_interrupts_init


    mov rcx, VECTOR_USB

    mov rdx, [xhci_base_mmio]

    call update_register_vector


.skip_usb:


    ; ==========================================================================
    ; AHCI / TGFS
    ; ==========================================================================

    call find_ahci_controller

    jc .skip_storage


    call init_ahci_controller


    xor rcx, rcx

    call vfs_mount_drive


    cmp rax, 1

    jne .skip_storage


    mov byte [tgfs_active], 1


    mov rcx, VECTOR_STORAGE

    lea rdx, [rel tgfs_load_and_map_file]

    call update_register_vector


.skip_storage:


    ; ==========================================================================
    ; UPDATE CHECK
    ; ==========================================================================

    cmp byte [tgfs_active], 1

    jne .skip_update_check


    call update_check

    cmp rax, 1

    jne .skip_update_check


    call update_apply


.skip_update_check:


    ; ==========================================================================
    ; SCHEDULER INIT
    ;
    ; Task 0 = kernel.
    ; ==========================================================================

    call scheduler_init


    ; ==========================================================================
    ; HID
    ; ==========================================================================

    call hid_init


    ; ==========================================================================
    ; BSOD
    ; ==========================================================================

    call bsod_init


    ; ==========================================================================
    ; SHELL
    ; ==========================================================================

    call shell_init


    ; ==========================================================================
    ; SERIAL
    ; ==========================================================================

    call serial_init


    ; ==========================================================================
    ; PIT
    ;
    ; Nadal mamy CLI.
    ; PIT może generować IRQ dopiero po utworzeniu poprawnego
    ; kontekstu task 0.
    ; ==========================================================================

    call pit_init


    ; ==========================================================================
    ; LOG STARTOWY
    ; ==========================================================================

    lea rsi, [rel msg_boot]

    call serial_log


    ; ==========================================================================
    ; START GUI / APPLICATION
    ; ==========================================================================

    cmp byte [tgfs_active], 1

    jne fallback_render


    ; ==========================================================================
    ; TGFS GUI
    ;
    ; Ładujemy aplikację.
    ; ==========================================================================

    xor rcx, rcx

    mov rdx, 5

    ; --------------------------------------------------------------------------
    ; TGFS LOAD ADDRESS
    ;
    ; 0x00800000 było błędne:
    ; - znajduje się poniżej bezpiecznego obszaru TGFS,
    ; - koliduje z obszarem zarezerwowanym przez PMM.
    ;
    ; tgfs_vfs.asm dopuszcza zakres:
    ;     0x04000000 - 0x06000000
    ;
    ; --------------------------------------------------------------------------

    mov r8, 0x04000000

    call tgfs_load_and_map_file


    ; --------------------------------------------------------------------------
    ; Sprawdź poprawność entry point.
    ; --------------------------------------------------------------------------

    cmp rax, 0

    je fallback_render

    cmp rax, -1

    je fallback_render


    ; --------------------------------------------------------------------------
    ; Zachowaj entry point.
    ; --------------------------------------------------------------------------

    mov r12, rax


    ; ==========================================================================
    ; PRZYDZIEL STRONĘ NA STOS NOWEGO ZADANIA
    ;
    ; NIE używamy już:
    ;
    ;     0x00A00000
    ;
    ; ponieważ ten adres nie był zarezerwowany przez PMM.
    ;
    ; pmm_alloc_page zwraca fizyczny adres strony.
    ; ==========================================================================

    call pmm_alloc_page

    test rax, rax

    jz fallback_render


    ; --------------------------------------------------------------------------
    ; Początek strony = dół stosu.
    ; Koniec strony = RAX + 4096.
    ; --------------------------------------------------------------------------

    add rax, 4096

    mov r13, rax


    ; ==========================================================================
    ; UTWÓRZ TASK
    ;
    ; RCX = entry point
    ; RDX = początkowy RSP
    ; ==========================================================================

    mov rcx, r12

    mov rdx, r13

    call scheduler_create_task


    ; --------------------------------------------------------------------------
    ; Sprawdź ID.
    ;
    ; RAX = -1 -> brak miejsca w tablicy tasków.
    ; ==========================================================================

    cmp rax, -1

    je fallback_render


    ; --------------------------------------------------------------------------
    ; Task został już oznaczony jako ready przez scheduler_create_task.
    ;
    ; Nie musimy drugi raz wywoływać scheduler_trigger_event().
    ; --------------------------------------------------------------------------

    jmp system_execute


; ==============================================================================
; FALLBACK GUI
; ==============================================================================

fallback_render:

    mov ecx, 150

    mov edx, 150

    mov r8d, 500

    mov r9d, 350

    call gui_draw_window

    call gui_refresh_screen


; ==============================================================================
; SYSTEM EXECUTION
; ==============================================================================

system_execute:

    ; ==========================================================================
    ; Dopiero tutaj włączamy IRQ.
    ;
    ; Scheduler został już zainicjalizowany.
    ; Task 0 będzie miał zapisany kontekst przy pierwszym PIT IRQ.
    ; ==========================================================================

    sti


kernel_idle_loop:

    call scheduler_event_loop

    jmp kernel_idle_loop


; ==============================================================================
; KERNEL PANIC
; ==============================================================================

kernel_panic:

    cli


panic_loop:

    hlt

    jmp panic_loop


; ==============================================================================
; DATA
; ==============================================================================

section .data

align 8


; ==============================================================================
; FRAMEBUFFER
; ==============================================================================

fb_address:
    dq 0


fb_size:
    dq 0


fb_width:
    dd 0


fb_height:
    dd 0


fb_pps:
    dd 0


fb_pixel_format:
    dd 0


; ==============================================================================
; UEFI MEMORY MAP
; ==============================================================================

mmap_ptr:
    dq 0


mmap_size:
    dq 0


mmap_descsz:
    dq 0


mmap_descver:
    dq 0


; ==============================================================================
; xHCI
; ==============================================================================

xhci_base_mmio:
    dq 0


; ==============================================================================
; TGFS
; ==============================================================================

tgfs_active:
    db 0


; ==============================================================================
; BOOT MESSAGE
; ==============================================================================

msg_boot:
    db "Kernel uruchomiony!", 0


; ==============================================================================
; KERNEL STACK