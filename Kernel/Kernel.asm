; ==============================================================================
;          BLITRUM OS - MAIN KERNEL
;          x86-64 / NASM
; ==============================================================================
;
; Aktualny etap:
;   UEFI
;   PMM
;   GDT
;   IDT / PIC
;   PIT
;   ACPI / MADT
;   Local APIC
;   AHCI / TGFS
;   GUI
;   HID
;   Scheduler
;
; ACPI:
;   BootInfo + 0x40 = RSDP
;   acpi_init()     = RSDP -> XSDT/RSDT -> MADT
;
; LAPIC:
;   wykrywany przez CPUID/MSR
;   ACPI MADT jest źródłem informacji o platformie
;
; UWAGA:
;   PIC + PIT nadal pozostają aktywne.
;   IOAPIC i routing IRQ zostaną wykonane w następnym etapie.
; ==============================================================================

bits 64

section .text

global _start

extern __bss_start
extern __bss_end


; ==============================================================================
; SYSTEM
; ==============================================================================

extern gdt_init
extern pit_init
extern bsod_init
extern serial_init
extern serial_log


; ==============================================================================
; HID / IDT
; ==============================================================================

extern hid_init
extern idt_init


; ==============================================================================
; PMM
; ==============================================================================

extern pmm_init
extern pmm_alloc_page


; ==============================================================================
; ACPI
; ==============================================================================

extern acpi_init
extern acpi_get_madt
extern acpi_get_lapic_address
extern acpi_get_lapic_count


; ==============================================================================
; LOCAL APIC
; ==============================================================================

extern lapic_init
extern lapic_available
extern lapic_get_id
extern lapic_eoi


; ==============================================================================
; GUI
; ==============================================================================

extern gui_init
extern gui_draw_window
extern gui_refresh_screen
extern gui_pixel_format


; ==============================================================================
; STORAGE
; ==============================================================================

extern find_ahci_controller
extern init_ahci_controller
extern vfs_mount_drive
extern tgfs_load_and_map_file


; ==============================================================================
; USB / AUDIO
; ==============================================================================

extern find_usb_controllers
extern usb_interrupts_init

extern find_hda_controller
extern init_hda_controller


; ==============================================================================
; SCHEDULER
; ==============================================================================

extern scheduler_init
extern scheduler_create_task
extern scheduler_trigger_event
extern scheduler_event_loop


; ==============================================================================
; SHELL
; ==============================================================================

extern shell_init
extern shell_run


; ==============================================================================
; AHS-TUS / UPDATE
; ==============================================================================

extern update_system_init
extern update_register_vector
extern update_check
extern update_apply
extern update_is_pending


; ==============================================================================
; AHS-TUS VECTORS
; ==============================================================================

VECTOR_AUDIO    equ 0
VECTOR_USB      equ 1
VECTOR_STORAGE  equ 2
VECTOR_GRAPHICS equ 3


; ==============================================================================
; GOP PIXEL FORMAT
; ==============================================================================

PIXEL_RED_GREEN_BLUE_RESERVED equ 0
PIXEL_BLUE_GREEN_RED_RESERVED equ 1


; ==============================================================================
; KERNEL ENTRY
; ==============================================================================

_start:

    cli


    ; ==========================================================================
    ; SPRAWDŹ BOOTINFO
    ; ==========================================================================

    test rcx, rcx

    jz kernel_panic


    ; ==========================================================================
    ; ZACHOWAJ ADRES BOOTINFO
    ;
    ; BootInfo:
    ;
    ; +0x00 framebuffer
    ; +0x08 framebuffer size
    ; +0x10 width
    ; +0x14 height
    ; +0x18 pixels per scanline
    ; +0x1C pixel format
    ; +0x20 memory map pointer
    ; +0x28 memory map size
    ; +0x30 descriptor size
    ; +0x38 descriptor version
    ; +0x40 ACPI RSDP
    ; ==========================================================================

    mov rbx, rcx


    ; ==========================================================================
    ; USTAW STOS KERNELA
    ; ==========================================================================

    lea rsp, [rel stack_top]

    and rsp, -16


    ; ==========================================================================
    ; ZAŁADUJ GDT
    ; ==========================================================================

    call gdt_init


    ; ==========================================================================
    ; WYCZYŚĆ .BSS
    ; ==========================================================================

    mov rdi, __bss_start

    mov rcx, __bss_end

    sub rcx, rdi

    xor rax, rax

    rep stosb


    ; ==========================================================================
    ; FRAMEBUFFER ADDRESS
    ; ==========================================================================

    mov r14, [rbx + 0x00]

    mov [fb_address], r14


    ; ==========================================================================
    ; FRAMEBUFFER SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x08]

    mov [fb_size], rax


    ; ==========================================================================
    ; SCREEN WIDTH
    ; ==========================================================================

    mov eax, [rbx + 0x10]

    mov [fb_width], eax


    ; ==========================================================================
    ; SCREEN HEIGHT
    ; ==========================================================================

    mov eax, [rbx + 0x14]

    mov [fb_height], eax


    ; ==========================================================================
    ; PIXELS PER SCANLINE
    ; ==========================================================================

    mov eax, [rbx + 0x18]

    mov [fb_pps], eax


    ; ==========================================================================
    ; GOP PIXEL FORMAT
    ; ==========================================================================

    mov eax, [rbx + 0x1C]

    mov [fb_pixel_format], eax

    mov [gui_pixel_format], eax


    ; ==========================================================================
    ; UEFI MEMORY MAP POINTER
    ; ==========================================================================

    mov rax, [rbx + 0x20]

    mov [mmap_ptr], rax


    ; ==========================================================================
    ; UEFI MEMORY MAP SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x28]

    mov [mmap_size], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR SIZE
    ; ==========================================================================

    mov rax, [rbx + 0x30]

    mov [mmap_descsz], rax


    ; ==========================================================================
    ; UEFI MEMORY DESCRIPTOR VERSION
    ; ==========================================================================

    mov rax, [rbx + 0x38]

    mov [mmap_descver], rax


    ; ==========================================================================
    ; ACPI RSDP
    ; ==========================================================================

    mov rax, [rbx + 0x40]

    mov [acpi_rsdp], rax


    ; ==========================================================================
    ; WALIDACJA BOOTINFO
    ; ==========================================================================

    cmp qword [fb_address], 0

    je kernel_panic


    cmp dword [fb_width], 0

    je kernel_panic


    cmp dword [fb_height], 0

    je kernel_panic


    cmp dword [fb_pps], 0

    je kernel_panic


    cmp qword [mmap_ptr], 0

    je kernel_panic


    cmp qword [mmap_size], 0

    je kernel_panic


    cmp qword [mmap_descsz], 0

    je kernel_panic


    ; ==========================================================================
    ; PMM INIT
    ;
    ; RCX = descriptor size
    ; R8  = memory map size
    ; R9  = memory map pointer
    ; ==========================================================================

    mov rcx, [mmap_descsz]

    mov r8, [mmap_size]

    mov r9, [mmap_ptr]

    call pmm_init


    ; ==========================================================================
    ; ACPI INIT
    ;
    ; RCX = RSDP
    ;
    ; Parser:
    ;   RSDP
    ;      |
    ;      +--> XSDT
    ;      |      |
    ;      |      +--> MADT
    ;      |
    ;      +--> RSDT fallback
    ;
    ; MADT:
    ;   - Local APIC
    ;   - IOAPIC
    ;   - ISO
    ; ==========================================================================

    mov rcx, [acpi_rsdp]

    test rcx, rcx

    jz .skip_acpi

    call acpi_init

    cmp rax, 1

    jne .skip_acpi


    ; --------------------------------------------------------------------------
    ; ACPI wykryte.
    ; --------------------------------------------------------------------------

    mov byte [acpi_active], 1


    ; --------------------------------------------------------------------------
    ; Zapamiętaj adres MADT.
    ; --------------------------------------------------------------------------

    call acpi_get_madt

    mov [acpi_madt], rax


    ; --------------------------------------------------------------------------
    ; Zapamiętaj Local APIC address z MADT.
    ; --------------------------------------------------------------------------

    call acpi_get_lapic_address

    mov [acpi_lapic_address], rax


    ; --------------------------------------------------------------------------
    ; Liczba wykrytych CPU/APIC.
    ; --------------------------------------------------------------------------

    call acpi_get_lapic_count

    mov [acpi_cpu_count], eax


.skip_acpi:


    ; ==========================================================================
    ; LOCAL APIC INIT
    ;
    ; Na tym etapie LAPIC jest tylko włączany.
    ;
    ; PIC/PIT nadal działają.
    ; ==========================================================================

    call lapic_init

    cmp rax, 1

    jne .skip_lapic


    mov byte [lapic_active], 1


    ; --------------------------------------------------------------------------
    ; Pobierz ID aktualnego CPU.
    ; --------------------------------------------------------------------------

    call lapic_get_id

    mov [lapic_boot_cpu_id], eax


.skip_lapic:


    ; ==========================================================================
    ; AHS-TUS
    ; ==========================================================================

    call update_system_init


    ; ==========================================================================
    ; IDT
    ;
    ; Nadal używamy PIC.
    ; ==========================================================================
    
    call idt_init


    ; ==========================================================================
    ; GUI / HDR
    ; ==========================================================================

    mov rcx, r14

    mov edx, [fb_width]

    mov r8d, [fb_height]

    mov r9d, [fb_pps]

    call gui_init


    ; ==========================================================================
    ; ZAREJESTRUJ GUI W AHS-TUS
    ; ==========================================================================

    mov rcx, VECTOR_GRAPHICS

    lea rdx, [rel gui_refresh_screen]

    call update_register_vector


    ; ==========================================================================
    ; AUDIO
    ; ==========================================================================

    call find_hda_controller

    jc .skip_audio


    call init_hda_controller


    mov rcx, VECTOR_AUDIO

    mov rdx, rax

    call update_register_vector


.skip_audio:


    ; ==========================================================================
    ; USB / xHCI
    ; ==========================================================================

    call find_usb_controllers

    jc .skip_usb


    mov [xhci_base_mmio], rax

    mov rcx, rax

    call usb_interrupts_init


    mov rcx, VECTOR_USB

    mov rdx, [xhci_base_mmio]

    call update_register_vector


.skip_usb:


    ; ==========================================================================
    ; AHCI / TGFS
    ; ==========================================================================

    call find_ahci_controller

    jc .skip_storage


    call init_ahci_controller


    xor rcx, rcx

    call vfs_mount_drive


    cmp rax, 1

    jne .skip_storage


    mov byte [tgfs_active], 1


    mov rcx, VECTOR_STORAGE

    lea rdx, [rel tgfs_load_and_map_file]

    call update_register_vector


.skip_storage:


    ; ==========================================================================
    ; UPDATE CHECK
    ; ==========================================================================

    cmp byte [tgfs_active], 1

    jne .skip_update_check


    call update_check

    cmp rax, 1

    jne .skip_update_check


    call update_apply


.skip_update_check:


    ; ==========================================================================
    ; SCHEDULER INIT
    ;
    ; Task 0 = kernel.
    ; ==========================================================================

    call scheduler_init


    ; ==========================================================================
    ; HID
    ; ==========================================================================

    call hid_init


    ; ==========================================================================
    ; BSOD
    ; ==========================================================================

    call bsod_init


    ; ==========================================================================
    ; SHELL
    ; ==========================================================================

    call shell_init


    ; ==========================================================================
    ; SERIAL
    ; ==========================================================================

    call serial_init


    ; ==========================================================================
    ; PIT
    ;
    ; Nadal używamy PIT przez PIC.
    ;
    ; IOAPIC zostanie dodany później.
    ; ==========================================================================

    call pit_init


    ; ==========================================================================
    ; LOG STARTOWY
    ; ==========================================================================

    lea rsi, [rel msg_boot]

    call serial_log


    ; ==========================================================================
    ; START GUI / APPLICATION
    ; ==========================================================================

    cmp byte [tgfs_active], 1

    jne fallback_render


    ; ==========================================================================
    ; TGFS GUI
    ;
    ; Ładujemy aplikację.
    ; ==========================================================================

    xor rcx, rcx

    mov rdx, 5


    ; --------------------------------------------------------------------------
    ; TGFS LOAD ADDRESS
    ;
    ; Zakres obsługiwany przez tgfs_vfs.asm:
    ;
    ;     0x04000000 - 0x06000000
    ;
    ; 0x00800000 było błędne, ponieważ kolidowało z obszarem PMM.
    ; --------------------------------------------------------------------------

    mov r8, 0x04000000

    call tgfs_load_and_map_file


    ; --------------------------------------------------------------------------
    ; Sprawdź poprawność entry point.
    ; --------------------------------------------------------------------------

    cmp rax, 0

    je fallback_render


    cmp rax, -1

    je fallback_render


    ; --------------------------------------------------------------------------
    ; Zachowaj entry point.
    ; --------------------------------------------------------------------------

    mov r12, rax


    ; ==========================================================================
    ; PRZYDZIEL STRONĘ NA STOS NOWEGO ZADANIA
    ; ==========================================================================

    call pmm_alloc_page

    test rax, rax

    jz fallback_render


    ; --------------------------------------------------------------------------
    ; Początek strony = dół stosu.
    ; Koniec strony = RAX + 4096.
    ; --------------------------------------------------------------------------

    add rax, 4096

    mov r13, rax


    ; ==========================================================================
    ; UTWÓRZ TASK
    ;
    ; RCX = entry point
    ; RDX = początkowy RSP
    ; ==========================================================================

    mov rcx, r12

    mov rdx, r13

    call scheduler_create_task


    ; --------------------------------------------------------------------------
    ; RAX = ID taska
    ; RAX = -1 -> brak miejsca
    ; --------------------------------------------------------------------------

    cmp rax, -1

    je fallback_render


    ; --------------------------------------------------------------------------
    ; Task został już oznaczony jako READY.
    ; --------------------------------------------------------------------------

    jmp system_execute


; ==============================================================================
; FALLBACK GUI
; ==============================================================================

fallback_render:

    mov ecx, 150

    mov edx, 150

    mov r8d, 500

    mov r9d, 350

    call gui_draw_window

    call gui_refresh_screen


; ==============================================================================
; SYSTEM EXECUTION
; ==============================================================================

system_execute:

    ; ==========================================================================
    ; Dopiero tutaj włączamy IRQ.
    ;
    ; Scheduler został już zainicjalizowany.
    ;
    ; Aktualnie:
    ;
    ;   PIT -> PIC -> IDT
    ;
    ; Docelowo:
    ;
    ;   PIT/IRQ -> IOAPIC -> LAPIC -> IDT
    ;
    ; ==========================================================================
    
    sti


kernel_idle_loop:

    call scheduler_event_loop

    jmp kernel_idle_loop


; ==============================================================================
; KERNEL PANIC
; ==============================================================================

kernel_panic:

    cli


panic_loop:

    hlt

    jmp panic_loop


