; ==============================================================================
;              BLITRUM OS - GLOBAL DESCRIPTOR TABLE
;              x86-64 / NASM
; ==============================================================================
;
; GDT używana przez kernel po przejściu z UEFI.
;
; Selektory:
;
;   0x00 = NULL
;   0x08 = RESERVED
;   0x10 = KERNEL DATA
;   0x18 = KERNEL CODE
;   0x20 = RESERVED FOR TSS
;
; ==============================================================================

bits 64

section .text

global gdt_init

; ==============================================================================
; GDT SELECTORS
; ==============================================================================

GDT_NULL        equ 0x00
GDT_RESERVED    equ 0x08
GDT_KERNEL_DATA equ 0x10
GDT_KERNEL_CODE equ 0x18
GDT_TSS         equ 0x20


; ==============================================================================
; gdt_init
;
; Ładuje własną GDT Blitrum OS.
;
; Po powrocie:
;
;   CS = 0x18
;   SS = 0x10
;   DS = 0x10
;   ES = 0x10
;   FS = 0
;   GS = 0
;
; ==============================================================================

gdt_init:

    cli

    ; --------------------------------------------------------------------------
    ; Załaduj GDTR
    ; --------------------------------------------------------------------------

    lgdt [rel gdt_pointer]


    ; --------------------------------------------------------------------------
    ; Przeładuj CS.
    ;
    ; Nie można wykonać zwykłego:
    ;
    ;     mov cs, ...
    ;
    ; dlatego wykonujemy daleki powrót.
    ; --------------------------------------------------------------------------

    push qword GDT_KERNEL_CODE

    lea rax, [rel .reload_cs]

    push rax

    retfq


.reload_cs:

    ; --------------------------------------------------------------------------
    ; Załaduj segmenty danych.
    ; --------------------------------------------------------------------------

    mov ax, GDT_KERNEL_DATA

    mov ds, ax
    mov es, ax
    mov ss, ax

    ; FS/GS pozostają wyzerowane.
    xor eax, eax

    mov fs, ax
    mov gs, ax

    ret


; ==============================================================================
; GDT
; ==============================================================================

section .data

align 8

gdt_start:

    ; --------------------------------------------------------------------------
    ; 0x00 - NULL DESCRIPTOR
    ; --------------------------------------------------------------------------

    dq 0x0000000000000000


    ; --------------------------------------------------------------------------
    ; 0x08 - RESERVED
    ; --------------------------------------------------------------------------

    dq 0x0000000000000000


    ; --------------------------------------------------------------------------
    ; 0x10 - KERNEL DATA
    ;
    ; Base  = 0
    ; Limit = 4 GiB
    ; Present
    ; Ring 0
    ; Data
    ; Read/Write
    ; --------------------------------------------------------------------------

    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 0x92
    db 0xCF
    db 0x00


    ; --------------------------------------------------------------------------
    ; 0x18 - KERNEL CODE
    ;
    ; Base  = 0
    ; Limit = 4 GiB
    ; Present
    ; Ring 0
    ; Code
    ; Execute/Read
    ; Long Mode
    ; --------------------------------------------------------------------------

    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 0x9A
    db 0xAF
    db 0x00


    ; --------------------------------------------------------------------------
    ; 0x20 - RESERVED FOR TSS
    ; --------------------------------------------------------------------------

    dq 0x0000000000000000


gdt_end:


; ==============================================================================
; GDTR
; ==============================================================================

gdt_pointer:

    dw gdt_end - gdt_start - 1

    dq gdt_start