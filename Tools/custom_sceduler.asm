; ==============================================================================
; BLITRUM OS - BME-QD CUSTOM SCHEDULER
; x86-64 / NASM
; ==============================================================================
;
; BME-QD = Bit-Matrix Event-Driven Quantum Dispatcher
;
; Task:
;
;   Task 0       = kernel / idle
;   Task 1..63   = system tasks / applications
;
; Maksymalnie:
;
;   64 taski
;
; Ready mask:
;
;   bit N = task N jest gotowy do wykonania
;
;
; TIMER:
;
;   LAPIC Timer -> vector 0x20
;                -> lapic_timer_handler
;                -> scheduler_dispatch
;
; Software yield:
;
;   INT 0x80
;       -> scheduler_dispatch
;
;
; NIE używamy PIT jako aktywnego źródła ticka schedulera.
;
;
; KONTEKST:
;
;   RAX
;   RBX
;   RCX
;   RDX
;   RSI
;   RDI
;   RBP
;   R8
;   R9
;   R10
;   R11
;   R12
;   R13
;   R14
;   R15
;
;
; RAMKA IRETQ:
;
;   RIP
;   CS
;   RFLAGS
;
; Dla aktualnie używanego kernela wszystkie taski pracują w Ring 0.
;
; ==============================================================================

bits 64


; ==============================================================================
; PUBLIC
; ==============================================================================

global scheduler_init
global scheduler_create_task
global scheduler_trigger_event
global scheduler_yield
global scheduler_dispatch
global scheduler_event_loop
global scheduler_task_exit


; ==============================================================================
; EXTERNALS
; ==============================================================================

extern shell_run


; ==============================================================================
; CONSTANTS
; ==============================================================================

MAX_TASKS equ 64

KERNEL_TASK_ID equ 0

KERNEL_CODE_SELECTOR equ 0x18

INITIAL_RFLAGS equ 0x202


; ==============================================================================
; TASK CONTEXT LAYOUT
;
; scheduler_dispatch zapisuje 15 rejestrów:
;
;   +0   RAX
;   +8   RBX
;   +16  RCX
;   +24  RDX
;   +32  RSI
;   +40  RDI
;   +48  RBP
;   +56  R8
;   +64  R9
;   +72  R10
;   +80  R11
;   +88  R12
;   +96  R13
;   +104 R14
;   +112 R15
;
; Następnie:
;
;   +120 RIP
;   +128 CS
;   +136 RFLAGS
;
; Po odtworzeniu 15 GPR:
;
;   RSP = context + 120
;
; IRETQ pobiera:
;
;   RIP
;   CS
;   RFLAGS
;
; ==============================================================================


; ==============================================================================
; DATA
; ==============================================================================

section .data

align 8


; ==============================================================================
; RSP KAŻDEGO TASKA
; ==============================================================================

task_rsp_table:

    times MAX_TASKS dq 0


; ==============================================================================
; READY BITMASK
;
; bit 0 = kernel
; bit 1 = task 1
; ...
; bit 63 = task 63
; ==============================================================================

system_ready_mask:

    dq 0


; ==============================================================================
; AKTUALNY TASK
; ==============================================================================

current_task_id:

    dd KERNEL_TASK_ID


; ==============================================================================
; DEBUG / STATYSTYKI
; ==============================================================================

align 8

scheduler_tick_count:

    dq 0

scheduler_switch_count:

    dq 0

scheduler_idle_count:

    dq 0


; ==============================================================================
; CODE
; ==============================================================================

section .text


; ==============================================================================
; scheduler_init
;
; Inicjalizacja schedulera.
;
; Po init:
;
;   Task 0 = READY
;   current_task = 0
;
; ==============================================================================

scheduler_init:

    cli


    ; ==========================================================================
    ; WYCZYŚĆ TABELĘ RSP
    ; ==========================================================================

    lea rdi, [rel task_rsp_table]

    xor eax, eax

    mov ecx, MAX_TASKS

    rep stosq


    ; ==========================================================================
    ; TASK 0 = KERNEL
    ; ==========================================================================

    mov qword [rel system_ready_mask], 1

    mov dword [rel current_task_id], KERNEL_TASK_ID


    ; ==========================================================================
    ; STATYSTYKI
    ; ==========================================================================

    mov qword [rel scheduler_tick_count], 0

    mov qword [rel scheduler_switch_count], 0

    mov qword [rel scheduler_idle_count], 0


    ret


; ==============================================================================
; scheduler_create_task
;
; WEJŚCIE:
;
;   RCX = adres funkcji taska
;   RDX = górny adres zaalokowanego stosu
;
; WYJŚCIE:
;
;   RAX = ID taska
;   RAX = -1 przy błędzie
;
;
; TASK START:
;
; Po pierwszym IRETQ:
;
;   RIP     = funkcja taska
;   CS      = 0x18
;   RFLAGS  = 0x202
;   RSP     = adres za początkową ramką
;
; Na RSP znajduje się adres:
;
;   scheduler_task_exit
;
; Jeżeli funkcja taska wykona RET, przejdzie do scheduler_task_exit.
;
; ==============================================================================

scheduler_create_task:

    push rbx
    push rcx
    push rdx
    push rdi
    push rsi
    push r8


    ; ==========================================================================
    ; WALIDACJA FUNKCJI
    ; ==========================================================================

    test rcx, rcx

    jz .invalid_task


    ; ==========================================================================
    ; WALIDACJA STOSU
    ; ==========================================================================

    test rdx, rdx

    jz .invalid_task


    ; ==========================================================================
    ; ZNAJDŹ WOLNY SLOT
    ;
    ; Task 0 jest zarezerwowany dla kernela.
    ; ==========================================================================

    mov edi, 1


.find_slot:

    cmp edi, MAX_TASKS

    jae .no_slot


    cmp qword [rel task_rsp_table + rdi * 8], 0

    je .slot_found


    inc edi

    jmp .find_slot


.no_slot:

    mov rax, -1

    jmp .create_done


.invalid_task:

    mov rax, -1

    jmp .create_done


; ==============================================================================
; SLOT ZNALEZIONY
; ==============================================================================

.slot_found:

    mov rbx, rdi


    ; ==========================================================================
    ; ZAPAMIĘTAJ ENTRY POINT
    ; ==========================================================================

    mov rsi, rcx


    ; ==========================================================================
    ; ZACHOWAJ GÓRĘ STOSU
    ;
    ; Potrzebujemy jej do sprawdzenia zawinięcia po odejmowaniu.
    ; ==========================================================================

    mov r8, rdx


    ; ==========================================================================
    ; WYRÓWNANIE DO 16 BAJTÓW
    ; ==========================================================================

    and rdx, -16


    ; ==========================================================================
    ; ZAREZERWUJ OBSZAR KONTEXTU
    ;
    ; Potrzebujemy:
    ;
    ;   15 qwords GPR       = 120 bajtów
    ;   3 qwords IRET       = 24 bajty
    ;   1 qword return      = 8 bajtów
    ;
    ; Razem minimum:
    ;
    ;   152 bajty
    ;
    ; Rezerwujemy 256 bajtów dla zapasu.
    ;
    ; RSP context = top - 248
    ;
    ; ==========================================================================

    sub rdx, 248


    ; ==========================================================================
    ; SPRAWDZENIE ZAWINIĘCIA
    ;
    ; Po poprawnym odjęciu:
    ;
    ;   RDX < R8
    ;
    ; Jeżeli RDX >= R8, nastąpiło zawinięcie.
    ; ==========================================================================

    cmp rdx, r8

    jae .invalid_stack


    ; ==========================================================================
    ; WYGENERUJ POCZĄTKOWY KONTEKST
    ; ==========================================================================

    mov rdi, rdx

    xor eax, eax

    mov ecx, 15

    rep stosq


    ; ==========================================================================
    ; RAMKA IRETQ
    ;
    ; context + 120 = RIP
    ; context + 128 = CS
    ; context + 136 = RFLAGS
    ; ==========================================================================


    ; ==========================================================================
    ; RIP
    ; ==========================================================================

    mov [rdx + 120], rsi


    ; ==========================================================================
    ; CS
    ; ==========================================================================

    mov qword [rdx + 128], KERNEL_CODE_SELECTOR


    ; ==========================================================================
    ; RFLAGS
    ;
    ; IF = 1
    ; Reserved bit 1 = 1
    ; ==========================================================================

    mov qword [rdx + 136], INITIAL_RFLAGS


    ; ==========================================================================
    ; RETURN ADDRESS
    ;
    ; Po IRETQ:
    ;
    ;   RSP = context + 144
    ;
    ; Pierwsza instrukcja taska działa normalnie.
    ;
    ; Gdy task wykona RET:
    ;
    ;   RIP = scheduler_task_exit
    ;
    ; ==========================================================================

    lea rsi, [rel scheduler_task_exit]

    mov [rdx + 144], rsi


    ; ==========================================================================
    ; ZAPISZ RSP TASKA
    ; ==========================================================================

    mov [rel task_rsp_table + rbx * 8], rdx


    ; ==========================================================================
    ; TASK READY
    ; ==========================================================================

    lock bts [rel system_ready_mask], rbx


    ; ==========================================================================
    ; ZWRÓĆ ID
    ; ==========================================================================

    mov rax, rbx

    jmp .create_done


; ==============================================================================
; NIEPRAWIDŁOWY STOS
; ==============================================================================

.invalid_stack:

    mov rax, -1

    jmp .create_done


; ==============================================================================
; KONIEC
; ==============================================================================

.create_done:

    pop r8
    pop rsi
    pop rdi
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; scheduler_trigger_event
;
; WEJŚCIE:
;
;   RCX = ID taska
;
; Działanie:
;
;   ustawia bit READY.
;
; Funkcja może być wywołana również z ISR.
;
; ==============================================================================

scheduler_trigger_event:

    ; ==========================================================================
    ; VALIDATE TASK ID
    ; ==========================================================================

    cmp rcx, MAX_TASKS

    jae .event_done


    ; ==========================================================================
    ; TASK MUSI MIEĆ KONTEKST
    ; ==========================================================================

    cmp qword [rel task_rsp_table + rcx * 8], 0

    je .event_done


    ; ==========================================================================
    ; USTAW READY
    ; ==========================================================================

    lock bts [rel system_ready_mask], rcx


.event_done:

    ret


; ==============================================================================
; scheduler_yield
;
; Wymusza natychmiastowe przejście przez dispatcher.
;
; ==============================================================================

scheduler_yield:

    int 0x80

    ret


; ==============================================================================
; scheduler_dispatch
;
; GŁÓWNY DISPATCHER.
;
; Wywoływany przez:
;
;   LAPIC Timer
;       -> vector 0x20
;
;   INT 0x80
;
;
; WEJŚCIE:
;
;   CPU posiada już ramkę:
;
;       RIP
;       CS
;       RFLAGS
;
; Dispatcher dokłada GPR i zapisuje RSP.
;
; ==============================================================================

scheduler_dispatch:


    ; ==========================================================================
    ; ZAPIS GPR
    ; ==========================================================================

    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp

    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15


    ; ==========================================================================
    ; ZWIĘKSZ LICZNIK TICKÓW
    ; ==========================================================================

    inc qword [rel scheduler_tick_count]


    ; ==========================================================================
    ; AKTUALNY TASK
    ; ==========================================================================

    mov eax, [rel current_task_id]


    ; ==========================================================================
    ; SPRAWDŹ READY
    ; ==========================================================================

    bt [rel system_ready_mask], rax

    jc .current_task_alive


    ; ==========================================================================
    ; TASK NIE JEST READY
    ;
    ; Nie zapisujemy jego kontekstu ponownie.
    ; ==========================================================================

    mov qword [rel task_rsp_table + rax * 8], 0

    jmp .select_next_task


; ==============================================================================
; AKTUALNY TASK NADAL READY
; ==============================================================================

.current_task_alive:

    ; ==========================================================================
    ; ZAPISZ RSP
    ;
    ; RSP wskazuje teraz na:
    ;
    ;   R15
    ;   ...
    ;   RAX
    ;   RIP
    ;   CS
    ;   RFLAGS
    ;
    ; ==========================================================================

    mov [rel task_rsp_table + rax * 8], rsp


; ==============================================================================
; WYBÓR NASTĘPNEGO TASKA
; ==============================================================================

.select_next_task:

    ; ==========================================================================
    ; POBIERZ READY MASK
    ; ==========================================================================

    mov rdx, [rel system_ready_mask]

    test rdx, rdx

    jz .no_ready_task


    ; ==========================================================================
    ; START OD TASKA NASTĘPNEGO
    ; ==========================================================================

    mov eax, [rel current_task_id]

    inc eax

    and eax, MAX_TASKS - 1

    mov ecx, eax

    xor r8d, r8d


; ==============================================================================
; SZUKANIE
; ==============================================================================

.find_next:

    ; ==========================================================================
    ; Czy task jest READY?
    ; ==========================================================================

    bt rdx, rcx

    jc .found_task


    ; ==========================================================================
    ; Następny task
    ; ==========================================================================

    inc ecx

    and ecx, MAX_TASKS - 1

    inc r8d


    ; ==========================================================================
    ; Maksymalnie MAX_TASKS prób
    ; ==========================================================================

    cmp r8d, MAX_TASKS

    jb .find_next


    jmp .no_ready_task


; ==============================================================================
; ZNALEZIONO TASK
; ==============================================================================

.found_task:

    ; ==========================================================================
    ; Pobierz zapisany RSP.
    ; ==========================================================================

    mov rax, [rel task_rsp_table + rcx * 8]

    test rax, rax

    jz .invalid_ready_task


    ; ==========================================================================
    ; USTAW CURRENT TASK
    ; ==========================================================================

    mov [rel current_task_id], ecx


    ; ==========================================================================
    ; STATYSTYKA
    ; ==========================================================================

    inc qword [rel scheduler_switch_count]


    ; ==========================================================================
    ; ZAŁADUJ RSP
    ; ==========================================================================

    mov rsp, rax


    ; ==========================================================================
    ; ODTWÓRZ GPR
    ; ==========================================================================

    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8

    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax


    ; ==========================================================================
    ; POWRÓT DO TASKA
    ;
    ; IRETQ pobierze:
    ;
    ;   RIP
    ;   CS
    ;   RFLAGS
    ;
    ; ==========================================================================

    iretq


; ==============================================================================
; READY BIT = 1
; ALE RSP = 0
; ==============================================================================

.invalid_ready_task:

    ; ==========================================================================
    ; Usuń nieprawidłowy READY bit.
    ; ==========================================================================

    lock btr [rel system_ready_mask], rcx

    mov qword [rel task_rsp_table + rcx * 8], 0


    ; ==========================================================================
    ; Pobierz aktualną maskę.
    ; ==========================================================================

    mov rdx, [rel system_ready_mask]

    test rdx, rdx

    jz .no_ready_task


    ; ==========================================================================
    ; Szukaj ponownie od następnego taska.
    ; ==========================================================================

    mov eax, ecx

    inc eax

    and eax, MAX_TASKS - 1

    mov ecx, eax

    xor r8d, r8d

    jmp .find_next


; ==============================================================================
; BRAK READY TASKA
; ==============================================================================

.no_ready_task:

    ; ==========================================================================
    ; Jeżeli aktualny task nadal jest READY,
    ; wracamy do niego.
    ; ==========================================================================

    mov eax, [rel current_task_id]

    bt [rel system_ready_mask], rax

    jc .return_current


    ; ==========================================================================
    ; Nie ma absolutnie żadnego bezpiecznego kontekstu.
    ; ==========================================================================

    jmp scheduler_fatal


; ==============================================================================
; POWRÓT DO AKTUALNEGO TASKA
; ==============================================================================

.return_current:

    ; ==========================================================================
    ; Pobierz RSP.
    ; ==========================================================================

    mov eax, [rel current_task_id]

    mov rsp, [rel task_rsp_table + rax * 8]


    ; ==========================================================================
    ; Walidacja
    ; ==========================================================================

    test rsp, rsp

    jz scheduler_fatal


    ; ==========================================================================
    ; ODTWÓRZ GPR
    ; ==========================================================================

    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8

    pop rbp
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx
    pop rax


    ; ==========================================================================
    ; POWRÓT
    ; ==========================================================================

    iretq


; ==============================================================================
; scheduler_task_exit
;
; Wywoływany po zakończeniu taska.
;
; Task może zakończyć się:
;
;   ret
;
; wtedy RIP wskazuje tutaj.
;
; ==============================================================================

scheduler_task_exit:

    cli


    ; ==========================================================================
    ; Pobierz ID taska.
    ; ==========================================================================

    mov eax, [rel current_task_id]


    ; ==========================================================================
    ; TASK 0 = KERNEL
    ;
    ; Kernel nie może zostać usunięty.
    ; ==========================================================================

    test eax, eax

    jz .kernel_exit_protection


    ; ==========================================================================
    ; USUŃ READY BIT
    ; ==========================================================================

    lock btr [rel system_ready_mask], rax


    ; ==========================================================================
    ; USUŃ KONTEKST
    ; ==========================================================================

    mov qword [rel task_rsp_table + rax * 8], 0


    ; ==========================================================================
    ; WYWOŁAJ DISPATCHER
    ;
    ; INT 0x80 tworzy własną ramkę IRETQ.
    ;
    ; scheduler_dispatch nie wraca tutaj.
    ; ==========================================================================

    int 0x80


    ; ==========================================================================
    ; TEGO NIE POWINNO SIĘ OSIĄGNĄĆ
    ; ==========================================================================

    jmp scheduler_fatal


; ==============================================================================
; KERNEL TASK EXIT PROTECTION
; ==============================================================================

.kernel_exit_protection:

    sti

    ret


; ==============================================================================
; scheduler_event_loop
;
; Główna pętla systemowa.
;
; Shell może wykonywać pracę synchronicznie.
;
; LAPIC Timer niezależnie wywołuje scheduler_dispatch.
;
; ==============================================================================

scheduler_event_loop:

    push rax
    push rcx


    ; ==========================================================================
    ; Shell
    ; ==========================================================================

    call shell_run


    pop rcx
    pop rax


    ; ==========================================================================
    ; Jeśli shell wróci, pozostajemy w stanie idle.
    ;
    ; LAPIC Timer nadal może nas obudzić.
    ; ==========================================================================

.event_idle:

    hlt

    jmp .event_idle


; ==============================================================================
; scheduler_fatal
;
; Nie znaleziono żadnego poprawnego kontekstu.
;
; ==============================================================================

scheduler_fatal:

    cli


.scheduler_fatal_loop:

    hlt

    jmp .scheduler_fatal_loop