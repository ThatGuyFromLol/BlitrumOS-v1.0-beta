; ==============================================================================
; BLITRUM OS - UPDATE LOADER / AHS-TUS
; x86-64 / NASM
; ==============================================================================
;
; Bezpieczne ładowanie update.pkg:
;
; - sprawdzanie magic
; - sprawdzanie liczby modułów
; - sprawdzanie rozmiaru pakietu
; - sprawdzanie granic nagłówków
; - sprawdzanie data_offset + size
; - każdy moduł posiada własny slot 2 MiB
; - destination musi odpowiadać slotowi modułu
; - moduł nie może wyjść poza własny slot
; - sprawdzanie checksum modułu
; - statyczny skan bezpieczeństwa
; - backup starego wektora
; - hot-swap wektora
;
; FORMAT UPDATE.PKG
;
; +00  DWORD  magic = USPK
; +04  DWORD  version
; +08  DWORD  module count
; +0C  DWORD  reserved
; +10  QWORD  XOR checksum
; +18  module headers
;
; Header modułu = 64 bajty:
;
; +00 DWORD  Vector ID
; +04 DWORD  Size
; +08 QWORD  Destination
; +10 QWORD  Reserved
; +18 QWORD  Reserved
; +20 QWORD  Checksum
; +28 QWORD  Data offset
; +30 QWORD  Reserved
; +38 QWORD  Reserved
;
; ==============================================================================


bits 64


; ==============================================================================
; SEKCJA CODE
; ==============================================================================

section .text

global update_check
global update_verify
global update_apply
global update_rollback
global update_is_pending


extern tgfs_load_and_map_file

extern update_register_vector
extern update_get_vector_address

extern malicious_check_static


; ==============================================================================
; STAŁE
; ==============================================================================

; ------------------------------------------------------------------------------
; UPDATE PACKAGE
; ------------------------------------------------------------------------------

PKG_MAGIC           equ 0x4B505355
PKG_TGFS_ID         equ 99

PKG_LOAD_ADDR       equ 0x03200000


; ------------------------------------------------------------------------------
; MODULE SLOTS
;
; 16 modułów
; każdy moduł = 2 MiB
;
; Slot 0:
;   0x04000000 - 0x041FFFFF
;
; Slot 1:
;   0x04200000 - 0x043FFFFF
;
; ...
;
; Slot 15:
;   0x05E00000 - 0x05FFFFFF
;
; ------------------------------------------------------------------------------
 
MODULE_LOAD_BASE    equ 0x04000000
MODULE_SLOT_SIZE    equ 0x00200000
MODULE_AREA_END     equ 0x06000000

MODULE_SLOT_MASK    equ MODULE_SLOT_SIZE - 1


; ------------------------------------------------------------------------------
; LIMITS
; ------------------------------------------------------------------------------

MAX_MODULES         equ 16
MAX_VECTOR_ID       equ 31


; ------------------------------------------------------------------------------
; SATA
; ------------------------------------------------------------------------------

SATA_PORT           equ 0


; ==============================================================================
; SEKCJA DATA
; ==============================================================================

section .data


align 8


; ------------------------------------------------------------------------------
; Czy pakiet został poprawnie zweryfikowany.
; ------------------------------------------------------------------------------

pkg_loaded:
    db 0


; ------------------------------------------------------------------------------
; Liczba modułów w update.pkg.
; ------------------------------------------------------------------------------

pkg_module_count:
    dd 0


align 8


; ------------------------------------------------------------------------------
; Bazowy adres update.pkg.
; ------------------------------------------------------------------------------

pkg_base_addr:
    dq PKG_LOAD_ADDR


; ------------------------------------------------------------------------------
; Czy oczekuje aktualizacja.
; ------------------------------------------------------------------------------

update_pending:
    db 0


align 8


; ------------------------------------------------------------------------------
; ID wektora, który spowodował crash.
; ------------------------------------------------------------------------------

crash_vector_id:
    dd 0xFFFFFFFF


; ------------------------------------------------------------------------------
; Liczba poprawnie aktywowanych modułów.
; ------------------------------------------------------------------------------

updated_count:
    dd 0


; ------------------------------------------------------------------------------
; Backup starych adresów wektorów.
;
; 16 × 8 bajtów
; ------------------------------------------------------------------------------

align 8

backup_vectors:
    times MAX_MODULES dq 0


; ------------------------------------------------------------------------------
; ID wektorów, które zostały zaktualizowane.
;
; 16 × 4 bajty
; ------------------------------------------------------------------------------

align 4

updated_vector_ids:
    times MAX_MODULES dd 0


; ==============================================================================
; UPDATE CHECK
; ==============================================================================
;
; Ładuje update.pkg z TGFS i sprawdza jego poprawność.
;
; Zwraca:
;
; RAX = 1  -> poprawna aktualizacja
; RAX = 0  -> brak aktualizacji / błąd
;
; ==============================================================================

section .text


update_check:

    push rbx
    push rcx
    push rdx
    push r8
    push r9


    ; --------------------------------------------------------------------------
    ; Wyczyść stan.
    ; --------------------------------------------------------------------------

    mov byte [rel update_pending], 0
    mov byte [rel pkg_loaded], 0


    ; --------------------------------------------------------------------------
    ; Załaduj update.pkg.
    ;
    ; RCX = SATA port
    ; RDX = TGFS ID
    ; R8  = destination
    ; --------------------------------------------------------------------------

    mov rcx, SATA_PORT
    mov rdx, PKG_TGFS_ID
    mov r8, PKG_LOAD_ADDR

    call tgfs_load_and_map_file


    ; --------------------------------------------------------------------------
    ; TGFS zwrócił błąd.
    ; --------------------------------------------------------------------------

    cmp rax, -1
    je .not_found


    ; --------------------------------------------------------------------------
    ; TGFS zwrócił zero.
    ; --------------------------------------------------------------------------

    test rax, rax
    jz .not_found


    ; --------------------------------------------------------------------------
    ; Zweryfikuj pakiet.
    ; --------------------------------------------------------------------------

    call update_verify

    test rax, rax
    jz .not_found


    ; --------------------------------------------------------------------------
    ; Pakiet jest gotowy.
    ; --------------------------------------------------------------------------

    mov byte [rel update_pending], 1

    mov eax, 1

    jmp .exit


.not_found:

    mov byte [rel update_pending], 0
    mov byte [rel pkg_loaded], 0

    xor eax, eax


.exit:

    pop r9
    pop r8
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; UPDATE VERIFY
; ==============================================================================
;
; Sprawdza:
;
; 1. minimalny rozmiar nagłówka
; 2. magic
; 3. liczbę modułów
; 4. czy wszystkie nagłówki mieszczą się w pakiecie
; 5. checksum
;
; ==============================================================================

update_verify:

    push rbx
    push rcx
    push rdx
    push rsi
    push rdi


    ; --------------------------------------------------------------------------
    ; Początek pakietu.
    ; --------------------------------------------------------------------------

    mov rsi, PKG_LOAD_ADDR


    ; --------------------------------------------------------------------------
    ; Pakiet musi posiadać przynajmniej 24 bajty nagłówka.
    ; --------------------------------------------------------------------------

    mov rdx, [rel tgfs_last_file_size]

    cmp rdx, 24
    jb .bad


    ; --------------------------------------------------------------------------
    ; MAGIC
    ; --------------------------------------------------------------------------

    mov eax, [rsi]

    cmp eax, PKG_MAGIC
    jne .bad


    ; --------------------------------------------------------------------------
    ; MODULE COUNT
    ; --------------------------------------------------------------------------

    mov ecx, [rsi + 8]

    test ecx, ecx
    jz .bad

    cmp ecx, MAX_MODULES
    ja .bad

    mov [rel pkg_module_count], ecx


    ; --------------------------------------------------------------------------
    ; Oblicz rozmiar:
    ;
    ; 24 bajty nagłówka głównego
    ; +
    ; liczba modułów × 64
    ; --------------------------------------------------------------------------

    mov eax, ecx

    shl rax, 6

    add rax, 24

    jc .bad


    ; --------------------------------------------------------------------------
    ; Nagłówki muszą mieścić się w rzeczywistym pliku.
    ; --------------------------------------------------------------------------

    mov rdx, [rel tgfs_last_file_size]

    cmp rax, rdx
    ja .bad


    ; --------------------------------------------------------------------------
    ; CHECKSUM
    ;
    ; checksum znajduje się pod +10.
    ; --------------------------------------------------------------------------

    mov rbx, [rsi + 16]


    ; --------------------------------------------------------------------------
    ; XOR wykonywany po całej części nagłówkowej.
    ;
    ; Rozmiar jest wielokrotnością 8:
    ;
    ; 24 + 64*n
    ; --------------------------------------------------------------------------

    shr rax, 3

    mov rcx, rax

    test rcx, rcx
    jz .bad


    mov rsi, PKG_LOAD_ADDR + 24

    xor rax, rax


.xor_loop:

    xor rax, [rsi]

    add rsi, 8

    dec rcx

    jnz .xor_loop


    ; --------------------------------------------------------------------------
    ; Porównaj checksum.
    ; --------------------------------------------------------------------------

    cmp rax, rbx
    jne .bad


    ; --------------------------------------------------------------------------
    ; Pakiet poprawny.
    ; --------------------------------------------------------------------------

    mov byte [rel pkg_loaded], 1

    mov eax, 1

    jmp .exit


.bad:

    mov byte [rel pkg_loaded], 0

    xor eax, eax


.exit:

    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; UPDATE APPLY
; ==============================================================================
;
; Ładuje moduły z update.pkg.
;
; Każdy moduł posiada dokładnie jeden slot:
;
; slot = MODULE_LOAD_BASE + module_index * MODULE_SLOT_SIZE
;
; Moduł NIE może:
;
; - wejść przed swój slot
; - wejść za swój slot
; - być niewyrównany
; - używać innego slotu
; - przekroczyć 2 MiB
;
; ==============================================================================

update_apply:

    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15


    ; --------------------------------------------------------------------------
    ; Pakiet musi być zweryfikowany.
    ; --------------------------------------------------------------------------

    cmp byte [rel pkg_loaded], 1
    jne .not_ready


    ; --------------------------------------------------------------------------
    ; Wyzeruj licznik aktywowanych modułów.
    ; --------------------------------------------------------------------------

    mov dword [rel updated_count], 0


    ; --------------------------------------------------------------------------
    ; Pierwszy header modułu.
    ;
    ; PKG + 24
    ; --------------------------------------------------------------------------

    mov rsi, PKG_LOAD_ADDR + 24


    ; --------------------------------------------------------------------------
    ; r14d = indeks modułu.
    ; --------------------------------------------------------------------------

    xor r14d, r14d


    ; --------------------------------------------------------------------------
    ; r15d = liczba modułów.
    ; --------------------------------------------------------------------------

    mov r15d, [rel pkg_module_count]


; ==============================================================================
; MODULE LOOP
; ==============================================================================

.module_loop:

    cmp r14d, r15d
    jae .done


    ; --------------------------------------------------------------------------
    ; HEADER
    ;
    ; +00 Vector ID
    ; +04 Size
    ; +08 Destination
    ; +20 Checksum
    ; +28 Data offset
    ; --------------------------------------------------------------------------

    mov r12d, [rsi + 0]

    mov r13d, [rsi + 4]

    mov rdi,  [rsi + 8]

    mov rbx,  [rsi + 32]

    mov r10,  [rsi + 40]


    ; ==========================================================================
    ; VECTOR ID
    ; ==========================================================================

    cmp r12d, MAX_VECTOR_ID
    ja .skip_module


    ; ==========================================================================
    ; SIZE
    ; ==========================================================================

    test r13d, r13d
    jz .skip_module


    ; --------------------------------------------------------------------------
    ; Moduł nie może być większy niż jeden slot.
    ; --------------------------------------------------------------------------

    cmp r13d, MODULE_SLOT_SIZE
    ja .skip_module


    ; ==========================================================================
    ; DATA OFFSET
    ; ==========================================================================

    ; --------------------------------------------------------------------------
    ; Offset nie może wskazywać przed nagłówki.
    ; --------------------------------------------------------------------------

    cmp r10, 24
    jb .skip_module


    ; --------------------------------------------------------------------------
    ; Sprawdź:
    ;
    ; data_offset + size
    ;
    ; musi być <= rzeczywisty rozmiar update.pkg.
    ; --------------------------------------------------------------------------

    mov rax, r10

    add rax, r13

    jc .skip_module


    mov rdx, [rel tgfs_last_file_size]

    cmp rax, rdx
    ja .skip_module


    ; --------------------------------------------------------------------------
    ; Oblicz fizyczny adres źródła.
    ; --------------------------------------------------------------------------

    mov r11, PKG_LOAD_ADDR

    add r11, r10

    jc .skip_module


    ; ==========================================================================
    ; WYZNACZENIE SLOTU
    ; ==========================================================================
    ;
    ; Każdy moduł otrzymuje slot wynikający z indeksu.
    ;
    ; slot_start =
    ;
    ; MODULE_LOAD_BASE + index * MODULE_SLOT_SIZE
    ;
    ; ==========================================================================

    mov eax, MODULE_LOAD_BASE

    mov ecx, r14d

    imul rcx, MODULE_SLOT_SIZE

    add rax, rcx

    jc .skip_module

    mov rdx, rax


    ; --------------------------------------------------------------------------
    ; rdx = początek slotu.
    ; --------------------------------------------------------------------------
    ;
    ; slot_end = slot_start + 2 MiB
    ;
    ; --------------------------------------------------------------------------

    mov rax, rdx

    add rax, MODULE_SLOT_SIZE

    jc .skip_module

    mov rcx, rax


    ; ==========================================================================
    ; DESTINATION
    ; ==========================================================================

    ; --------------------------------------------------------------------------
    ; Jeśli destination = 0:
    ;
    ; automatycznie ustaw początek właściwego slotu.
    ; --------------------------------------------------------------------------

    test rdi, rdi
    jnz .destination_explicit


    mov rdi, rdx

    jmp .destination_ready


.destination_explicit:

    ; --------------------------------------------------------------------------
    ; Explicit destination musi być:
    ;
    ; 1. >= początek swojego slotu
    ; 2. < koniec swojego slotu
    ; 3. wyrównany do 2 MiB
    ; 4. dokładnie równy początkowi slotu
    ; --------------------------------------------------------------------------

    cmp rdi, rdx
    jne .skip_module


    cmp rdi, rcx
    jae .skip_module


    ; --------------------------------------------------------------------------
    ; Sprawdź wyrównanie 2 MiB.
    ; --------------------------------------------------------------------------

    test rdi, MODULE_SLOT_MASK
    jnz .skip_module


.destination_ready:

    ; ==========================================================================
    ; DODATKOWA KONTROLA OBSZARU MODUŁÓW
    ; ==========================================================================

    cmp rdi, MODULE_LOAD_BASE
    jb .skip_module


    cmp rdi, MODULE_AREA_END
    jae .skip_module


    ; --------------------------------------------------------------------------
    ; destination + size
    ; --------------------------------------------------------------------------

    mov rax, rdi

    add rax, r13

    jc .skip_module


    ; --------------------------------------------------------------------------
    ; Moduł musi zakończyć się przed końcem swojego slotu.
    ;
    ; rax = destination + size
    ; rcx = slot_end
    ; --------------------------------------------------------------------------

    cmp rax, rcx
    ja .skip_module


    ; --------------------------------------------------------------------------
    ; Dodatkowa kontrola końca całego obszaru.
    ; --------------------------------------------------------------------------

    cmp rax, MODULE_AREA_END
    ja .skip_module


    ; ==========================================================================
    ; STATIC SECURITY SCAN
    ; ==========================================================================
    ;
    ; RCX = source
    ; RDX = size
    ; R8  = checksum
    ;
    ; ==========================================================================

    push rsi
    push rdi
    push rbx
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15


    mov rcx, r11

    mov rdx, r13

    mov r8, rbx

    call malicious_check_static


    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop rbx
    pop rdi
    pop rsi


    ; --------------------------------------------------------------------------
    ; Jeśli skan wykrył problem -> pomiń moduł.
    ; --------------------------------------------------------------------------

    test rax, rax
    jnz .skip_module


    ; ==========================================================================
    ; COPY MODULE
    ; ==========================================================================

    mov r8, r11

    mov r9, rdi


    ; --------------------------------------------------------------------------
    ; Liczba pełnych QWORD.
    ; --------------------------------------------------------------------------

    mov ecx, r13d

    shr rcx, 3


.copy_qword:

    test rcx, rcx
    jz .copy_tail


    mov rax, [r8]

    mov [r9], rax


    add r8, 8

    add r9, 8


    dec rcx

    jmp .copy_qword


    ; ==========================================================================
    ; COPY TAIL
    ; ==========================================================================

.copy_tail:

    mov ecx, r13d

    and ecx, 7


    test ecx, ecx
    jz .module_copied


.copy_byte:

    mov al, [r8]

    mov [r9], al


    inc r8

    inc r9


    dec ecx

    jnz .copy_byte


    ; ==========================================================================
    ; MODULE COPIED
    ; ==========================================================================

.module_copied:

    ; --------------------------------------------------------------------------
    ; Pobierz stary adres wektora.
    ; --------------------------------------------------------------------------

    mov ecx, r12d

    call update_get_vector_address


    ; --------------------------------------------------------------------------
    ; Zapisz backup.
    ; --------------------------------------------------------------------------

    mov [rel backup_vectors + r14 * 8], rax


    ; --------------------------------------------------------------------------
    ; Zapamiętaj Vector ID.
    ; --------------------------------------------------------------------------

    mov [rel updated_vector_ids + r14 * 4], r12d


    ; ==========================================================================
    ; AKTYWACJA NOWEGO MODUŁU
    ; ==========================================================================

    mov rcx, r12

    mov rdx, rdi

    call update_register_vector


    ; --------------------------------------------------------------------------
    ; Jeśli rejestracja się nie udała:
    ;
    ; moduł pozostaje skopiowany, ale nie zostaje policzony jako aktywny.
    ; --------------------------------------------------------------------------

    test rax, rax
    jnz .skip_module


    inc dword [rel updated_count]


; ==============================================================================
; NEXT MODULE
; ==============================================================================

.skip_module:

    add rsi, 64

    inc r14d

    jmp .module_loop


; ==============================================================================
; UPDATE COMPLETE
; ==============================================================================

.done:

    mov byte [rel update_pending], 0

    mov eax, [rel updated_count]

    jmp .exit


; ==============================================================================
; NOT READY
; ==============================================================================

.not_ready:

    xor eax, eax


; ==============================================================================
; EXIT
; ==============================================================================

.exit:

    pop r15
    pop r14
    pop r13
    pop r12
    pop r11
    pop r10
    pop r9
    pop r8
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; UPDATE ROLLBACK
; ==============================================================================
;
; RCX = -1 -> rollback wszystkich
; RCX = ID  -> rollback konkretnego wektora
;
; ==============================================================================

update_rollback:

    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push r12
    push r13


    ; --------------------------------------------------------------------------
    ; Zapamiętaj żądanie rollback.
    ; --------------------------------------------------------------------------

    mov r12, rcx


    ; --------------------------------------------------------------------------
    ; Licznik wykonanych rollbacków.
    ; --------------------------------------------------------------------------

    xor r13d, r13d


    ; --------------------------------------------------------------------------
    ; Liczba zaktualizowanych modułów.
    ; --------------------------------------------------------------------------

    mov ebx, [rel updated_count]

    test ebx, ebx
    jz .nothing


    xor ecx, ecx


; ==============================================================================
; ROLLBACK LOOP
; ==============================================================================

.rollback_loop:

    cmp ecx, ebx
    jae .done


    ; --------------------------------------------------------------------------
    ; Pobierz Vector ID.
    ; --------------------------------------------------------------------------

    mov edx, [rel updated_vector_ids + rcx * 4]


    ; --------------------------------------------------------------------------
    ; RCX argument = -1 -> rollback wszystko.
    ; --------------------------------------------------------------------------

    cmp r12, -1
    je .rollback_this


    ; --------------------------------------------------------------------------
    ; Jeśli żądany ID różni się od aktualnego -> następny.
    ; --------------------------------------------------------------------------

    cmp rdx, r12
    jne .next


.rollback_this:

    ; --------------------------------------------------------------------------
    ; Index -> offset backupu.
    ; --------------------------------------------------------------------------

    mov rax, rcx

    shl rax, 3


    ; --------------------------------------------------------------------------
    ; Pobierz stary adres.
    ; --------------------------------------------------------------------------

    mov rsi, [rel backup_vectors + rax]


    ; --------------------------------------------------------------------------
    ; Brak starego adresu.
    ; --------------------------------------------------------------------------

    test rsi, rsi
    jz .clear_backup


    ; --------------------------------------------------------------------------
    ; Przywróć stary wektor.
    ; --------------------------------------------------------------------------

    push rcx


    mov rcx, rdx

    mov rdx, rsi

    call update_register_vector


    pop rcx


    inc r13d


.clear_backup:

    ; --------------------------------------------------------------------------
    ; Wyzeruj backup.
    ; --------------------------------------------------------------------------

    mov rax, rcx

    shl rax, 3

    mov qword [rel backup_vectors + rax], 0


.next:

    inc ecx

    jmp .rollback_loop


; ==============================================================================
; ROLLBACK DONE
; ==============================================================================

.done:

    mov eax, r13d


    pop r13
    pop r12
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; NOTHING TO ROLLBACK
; ==============================================================================

.nothing:

    xor eax, eax


    pop r13
    pop r12
    pop rdi
    pop rsi
    pop rdx
    pop rcx
    pop rbx

    ret


; ==============================================================================
; UPDATE IS PENDING
; ==============================================================================
;
; Zwraca:
;
; RAX = 1 -> aktualizacja oczekuje
; RAX = 0 -> brak aktualizacji
;
; ==============================================================================

update_is_pending:

    movzx eax, byte [rel update_pending]

    ret